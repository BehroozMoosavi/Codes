function near(x,y,tolerance,label)
    must(isequal(size(x),size(y)),['Shape mismatch: ' label]);
    must(all(isfinite(x(:)))&&all(isfinite(y(:))),['Nonfinite comparison: ' label]);
    d=max(abs(double(x(:))-double(y(:))));if isempty(d),d=0;end
    must(d<=tolerance,sprintf('%s differs by %.17g (tolerance %.17g).',label,d,tolerance));
end

