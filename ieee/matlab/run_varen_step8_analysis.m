function [runDir,zipPath] = run_varen_step8_analysis(step7Location)
%RUN_VAREN_STEP8_ANALYSIS Final saved-forecast analysis. NO model refitting.
% [folder,zipFile]=run_varen_step8_analysis(completedStep7Folder)
% Also accepts its step7_full_results.mat; no argument opens a file picker.
% Keep the complete Step7 folder or extracted results ZIP together.
% All input files remain read-only. Every call creates a new output folder.
%
% Frozen revision-stage exploratory analysis: full common physical-hour
% series; Bartlett HAC lags [168 24 48 720], primary display168; three VA-REN
% pairs (StaticEN, FixedEN05, LSBoost24h). Two-sided MSE/MAE loss tests,
% pointwise paired effect CIs, Holm p-value adjustments within each family.
% Secondary joint moment tests use constant, causal normalized volatility,
% and the two prespecified Pacific clock-window indicators. No compressed
% clock-window inference, forecast tuning, resampling, or random draws.

    started=tic; callerRNG=rng;
    rngCleanup=onCleanup(@()rng(callerRNG)); %#ok<NASGU>
    wrapperPath=[mfilename('fullpath') '.m'];wrapperSource=fileread(wrapperPath);
    corePath=which('varen_forecast_inference'); testPath=which('test_varen_forecast_inference');
    must(~isempty(corePath) && ~isempty(testPath), ...
        'Put varen_forecast_inference.m and test_varen_forecast_inference.m beside this wrapper.');
    coreSource=fileread(corePath); testSource=fileread(testPath);
    if nargin<1 || isempty(step7Location)
        [f,p]=uigetfile('step7_full_results.mat','Select completed Step 7 results');
        if isequal(f,0),error('VAREN:Step8Cancelled','No Step 7 result was selected.');end
        step7Location=fullfile(p,f);
    end
    step7Dir=resolveStep7(step7Location);
    baseDir=fileparts(wrapperPath);[~,token]=fileparts(tempname(baseDir));
    runDir=fullfile(baseDir,['step8_analysis_' token]);
    [ok,msg]=mkdir(runDir);if ~ok,error('VAREN:Step8Folder','%s',msg);end
    zipPath=fullfile(runDir,'step8_analysis_results.zip');
    copyfile(wrapperPath,fullfile(runDir,'run_varen_step8_analysis.m'));
    copyfile(corePath,fullfile(runDir,'varen_forecast_inference.m'));
    copyfile(testPath,fullfile(runDir,'test_varen_forecast_inference.m'));
    readmePath=fullfile(baseDir,'README_STEP8.txt');
    if isfile(readmePath),copyfile(readmePath,fullfile(runDir,'README_STEP8.txt'));end
    oldDiaryFile=get(0,'DiaryFile');oldDiaryState=get(0,'Diary');
    diaryCleanup=onCleanup(@()restoreDiary(oldDiaryFile,oldDiaryState)); %#ok<NASGU>
    diary(fullfile(runDir,'step8_console.txt'));
    try
        fprintf('\nVA-REN REVISION: STEP 8 SAVED-FORECAST ANALYSIS\nRevision 1.0; MATLAB %s\n',version);
        fprintf('Step 7 folder: %s\nOutput folder: %s\n',step7Dir,runDir);
        fprintf('No forecasts or model fitting. All saved input files remain read-only.\n');
        fprintf('Running deterministic inference self-tests.\n');
        selfTest=test_varen_forecast_inference;
        must(isstruct(selfTest) && isfield(selfTest,'Status') && strcmp(selfTest.Status,'PASS'), ...
            'Inference self-test did not return PASS.');
        must(isequal(callerRNG,rng),'Self-tests changed the caller RNG state.');
        save(fullfile(runDir,'step8_self_tests.mat'),'selfTest','-v7.3');
        if isfield(selfTest,'Checks') && istable(selfTest.Checks)
            writetable(selfTest.Checks,fullfile(runDir,'step8_self_tests.csv'));
        end
        F=load(fullfile(step7Dir,'step7_full_results.mat'));
        I=load(fullfile(step7Dir,'step7_inputs.mat'));
        H=load(fullfile(step7Dir,'step7_reference48.mat'),'Br','Ar','Sr');
        fprintf('Checking source identity, common origins, held counts and forecast reproduction.\n');
        validateStep7(step7Dir,F,I,H);
        D=I.D;R=I.linear.R;LA=I.linear.A;B=F.B;
        timeUTC=B.TimeUTC;timePT=timeUTC;timePT.TimeZone='America/Los_Angeles';
        raw=B.RawIndex;y=B.TargetMW;names=[R.ModelNames {B.ModelName}];
        pred=[R.PredictionMW B.PredictionMW];seconds=[R.RuntimeSeconds B.RuntimeSeconds];
        fprintf('Recomputing 48-hour past-only volatility and 2019 normalization.\n');
        [volatility,unclippedVolatility,normalizedVolatility,alpha,volatilityCalibration]= ...
            verifyVolatility(D,LA,R);
        [labels,masks]=subsetMasks(timePT);
        accuracy=accuracyTable(y,pred,names,seconds);
        subsets=table();
        for j=1:numel(labels)
            ix=masks{j};q=accuracyTable(y(ix),pred(ix,:),names,seconds(ix,:));
            q.Subset=repmat(labels(j),numel(names),1);subsets=[subsets;q]; %#ok<AGROW>
        end
        compareAccuracy(accuracy,F.metrics,'Step 7 overall accuracy');
        compareAccuracy(subsets,F.subsets,'Step 7 subset accuracy');
        h=hour(timePT);
        instruments=[ones(numel(y),1),normalizedVolatility,double(h>=10 & h<=14),double(h>=16 & h<=21)];
        instrumentNames={'Constant','PastNormalizedVolatility','Midday10to14','Evening16to21'};
        opts=struct('HACLags',[168 24 48 720],'PrimaryHACLag',168, ...
            'PairNames',{{'VAREN','StaticEN';'VAREN','FixedEN05';'VAREN','LSBoost24h'}}, ...
            'Instruments',instruments,'InstrumentNames',{instrumentNames});
        sourceMetadata=D.sourceMetadata;sourceProtocol=D.protocol;
        analysisProtocol=struct('Revision','1.0','AnalysisStatus','Revision-stage exploratory', ...
            'HACLagsHours',opts.HACLags,'PrimaryDisplayHACLagHours',168, ...
            'PairNames',{opts.PairNames},'InstrumentNames',{instrumentNames}, ...
            'ForecastsRefit',false,'CommonPhysicalHours',34343, ...
            'LossDirection','Comparator B minus focal model A; positive favors A', ...
            'TimeWindows','Pacific 10:00-14:00 and 16:00-21:00 interval starts, inclusive', ...
            'IntervalType','Pointwise asymptotic 95%; not simultaneous', ...
            'ConditionalTest','Secondary joint moments; nondirectional', ...
            'Multiplicity','Holm within each test type, loss and bandwidth across all three planned pairs; undefined tests remain in the family', ...
            'YearAndClockSubsets','Descriptive; no tests on compressed subsets', ...
            'SourceStep7Folder',step7Dir,'MATLABVersion',version);
        save(fullfile(runDir,'step8_analysis_inputs.mat'),'timeUTC','timePT','raw','y','pred','names', ...
            'instruments','instrumentNames','volatility','unclippedVolatility', ...
            'normalizedVolatility','alpha','volatilityCalibration','sourceMetadata','sourceProtocol', ...
            'analysisProtocol','-v7.3');
        fprintf('Computing paired effects and HAC inference at lags 168, 24, 48 and 720 hours.\n');
        analysisClock=tic;[T,inferenceDiagnostics]=varen_forecast_inference(y,pred,names,opts);
        inferenceSeconds=toc(analysisClock);
        must(isequal(callerRNG,rng),'Analysis changed the caller RNG state.');
        must(strcmp(coreSource,fileread(corePath)) && strcmp(testSource,fileread(testPath)) && ...
            strcmp(wrapperSource,fileread(wrapperPath)), ...
            'Wrapper, analysis or self-test source changed while this run was active.');
        validateInferenceTables(T,opts,numel(y));
        primary=primaryTable(T);
        volDiagnostics=volatilityTable(labels,masks,volatility,unclippedVolatility,normalizedVolatility,alpha);
        timing=timingTable(names,seconds,R,B);
        lambdaEndpoints=lambdaTable(R,LA);
        cycleDistribution=cycleTable(B);
        writetable(accuracy,fullfile(runDir,'step8_accuracy.csv'));
        writetable(subsets,fullfile(runDir,'step8_accuracy_by_subset.csv'));
        writetable(T.DM,fullfile(runDir,'step8_dm_tests.csv'));
        writetable(T.Effects,fullfile(runDir,'step8_effect_intervals.csv'));
        writetable(T.GW,fullfile(runDir,'step8_gw_joint_tests.csv'));
        writetable(primary,fullfile(runDir,'step8_primary_comparisons.csv'));
        writetable(volDiagnostics,fullfile(runDir,'step8_volatility_diagnostics.csv'));
        writetable(timing,fullfile(runDir,'step8_model_timing.csv'));
        writetable(lambdaEndpoints,fullfile(runDir,'step8_lambda_endpoints.csv'));
        writetable(cycleDistribution,fullfile(runDir,'step8_cycle_distribution.csv'));
        intervalTable=table(raw,utcText(timeUTC),utcText(D.intervalEndUTC(raw)), ...
            'VariableNames',{'RawIndex','IntervalStartUTC','IntervalEndUTC'});
        writetable(intervalTable,fullfile(runDir,'step8_interval_index.csv'));
        elapsedSeconds=toc(started);
        save(fullfile(runDir,'step8_analysis_results.mat'),'T','inferenceDiagnostics','primary', ...
            'accuracy','subsets','volDiagnostics','timing','lambdaEndpoints','cycleDistribution', ...
            'analysisProtocol','selfTest','inferenceSeconds','elapsedSeconds','-v7.3');
        summary=sprintf([ ...
            'VA-REN REVISION: STEP 8 SAVED-FORECAST ANALYSIS\nRevision 1.0; MATLAB %s\n\n' ...
            'STEP8_STATUS: PASS\nSELF_TEST_STATUS: PASS\nINPUT_VALIDATION: PASS\n' ...
            'RNG_RESTORATION_CHECK: PASS\nFORECASTS_REFIT: NO\nFORECAST_ORIGINS: 34343\n' ...
            'ALIGNED_OUTPUTS: 8\nDISTINCT_FORECAST_RULES: 7\n\n' ...
            'Primary displayed analysis: full-sample MSE, Bartlett HAC lag 168 elapsed hours.\n' ...
            'Sensitivity bandwidths: 24, 48 and 720 hours; no bandwidth selected by p-value.\n' ...
            'All analyses are revision-stage exploratory, not preregistered confirmatory tests.\n' ...
            'DM tests are two-sided asymptotic loss-differential comparisons.\n' ...
            'Gains are comparator minus VA-REN; positive values favor VA-REN.\n' ...
            'RMSE/MAE effect intervals are pointwise asymptotic 95%% intervals, not simultaneous.\n' ...
            'Holm p-values adjust all three planned pairs separately by test, loss and bandwidth.\n' ...
            'Undefined tests remain in the multiplicity family and retain undefined reported p-values.\n' ...
            'GW-style tests are secondary joint conditional-moment tests, with nondirectional p-values.\n' ...
            'Instruments: constant, causal normalized volatility, Pacific midday and evening indicators.\n' ...
            'Year and clock-window results are descriptive only; no compressed-subset inference.\n' ...
            'Identical StaticEN/LASSO predictions are reported once for comparison inference.\n\n' ...
            'Inference assumes suitable weak dependence, finite relevant moments, and sufficient stability\n' ...
            'for the stated asymptotic approximations. These assumptions are not certified by this script.\n' ...
            'HAC does not correct arbitrary nonstationarity. A failure to reject is not equivalence.\n' ...
            'Statistical significance alone does not establish practical or operational importance.\n' ...
            'Runtime comparisons reuse separate runs; tuning budgets differ and this is not a microbenchmark.\n' ...
            'No settings, predictors, forecasts or source files were changed.\n' ...
            'Target remains hourly system demand, not solar-subtracted net load.\n\n' ...
            'Inference-core time: %.3f seconds\nAnalysis elapsed before final packaging: %.3f seconds\n' ...
            'Return step8_analysis_results.zip for final manuscript and reviewer-response preparation.\n'], ...
            version,inferenceSeconds,elapsedSeconds);
        writeText(fullfile(runDir,'step8_summary.txt'),summary);
        fprintf('\n%s\n',summary);
        disp(primary(:,{'ModelB','RMSE_Gain_MW','RMSE_CI95_Lower_MW','RMSE_CI95_Upper_MW', ...
            'MSE_DM_P_TwoSided','MSE_DM_P_Holm','Secondary_MSE_GW_P_Joint','DM_Status','GW_Status'}));
        disp(volDiagnostics(1:3,:));
        diary('off');packageResults(runDir,zipPath);
        fprintf('Upload ZIP: %s\n',zipPath);
    catch ME
        report=getReport(ME,'extended','hyperlinks','off');fprintf('\nSTEP8_STATUS: FAIL\n%s\n',report);
        try
            writeText(fullfile(runDir,'step8_summary.txt'),sprintf('STEP8_STATUS: FAIL\nFORECASTS_REFIT: NO\n\n%s\n',report));
            diary('off');failureZip=fullfile(runDir,'step8_failure.zip');packageResults(runDir,failureZip);
            fprintf('Upload failure ZIP: %s\n',failureZip);
        catch packagingError
            diary('off');fprintf('Could not package failure: %s\nReturn full error and step8_console.txt.\n',packagingError.message);
        end
        rethrow(ME);
    end
end

function folder=resolveStep7(location)
    must(ischar(location)||(isstring(location)&&isscalar(location)),'Supply one Step 7 path.');
    location=char(location);
    if isfolder(location),folder=location;
    else
        [folder,name,ext]=fileparts(location);
        must(strcmp([name ext],'step7_full_results.mat'),'Select step7_full_results.mat or its containing folder.');
        if isempty(folder),folder=pwd;end
    end
    files={'step7_full_results.mat','step7_inputs.mat','step7_reference48.mat', ...
        'step7_summary.txt','varen_lsboost_checkpointed_core.m','varen_lsboost_core.m'};
    for j=1:numel(files),must(isfile(fullfile(folder,files{j})),['Missing Step 7 file: ' files{j}]);end
    must(contains(fileread(fullfile(folder,'step7_summary.txt')),'STEP7_STATUS: PASS'), ...
        'The selected Step 7 run has not reported PASS.');
end

function validateStep7(folder,F,I,H)
    must(all(isfield(F,{'A','B','G','S','linearReference','metrics','subsets'})) && ...
        all(isfield(I,{'D','linear','calibration','coreSourceAtStart','originalCoreSourceAtStart'})) && ...
        all(isfield(H,{'Br','Ar','Sr'})),'Step 7 result/input variables are incomplete.');
    D=I.D;R=I.linear.R;LA=I.linear.A;B=F.B;A=F.A;G=F.G;S=F.S;C=I.calibration;
    must(strcmp(G.Status,'PASS') && strcmp(S.Status,'complete') && S.CompletedOrigins==34343 && ...
        S.TotalOrigins==34343 && G.ExpectedFullRetunes==1431 && G.PreflightOrigins==48 && ...
        G.PauseAfterOrigins==12 && G.PreflightRetunes==2,'Incomplete Step 7 validation or run status.');
    must(istable(G.Comparisons) && all(G.Comparisons.Passed) && ...
        all(G.Comparisons.MaxAbsoluteDifference<=G.Comparisons.AbsoluteTolerance), ...
        'Step 7 equivalence comparisons did not all pass.');
    must(strcmp(G.CoreSource,I.coreSourceAtStart) && ...
        strcmp(G.OriginalCoreSource,I.originalCoreSourceAtStart) && ...
        strcmp(G.CoreSource,fileread(fullfile(folder,'varen_lsboost_checkpointed_core.m'))) && ...
        strcmp(G.OriginalCoreSource,fileread(fullfile(folder,'varen_lsboost_core.m'))), ...
        'Saved Step 7 core source identities differ.');
    must(isdatetime(D.timeUTC) && iscolumn(D.timeUTC) && strcmp(D.timeUTC.TimeZone,'UTC') && ...
        numel(D.timeUTC)==43824 && ~any(isnat(D.timeUTC)) && all(diff(D.timeUTC)==hours(1)) && ...
        isdatetime(D.intervalEndUTC) && strcmp(D.intervalEndUTC.TimeZone,'UTC') && ...
        isequal(D.intervalEndUTC,D.timeUTC+hours(1)) && ...
        iscolumn(D.loadMW) && numel(D.loadMW)==43824 && isreal(D.loadMW) && ...
        all(isfinite(D.loadMW)) && all(D.loadMW>0) && ...
        islogical(D.isObserved) && isequal(size(D.isObserved),size(D.loadMW)) && all(D.isObserved), ...
        'Invalid complete hourly source arrays.');
    must(D.timeUTC(1)==datetime(2019,1,1,8,0,0,'TimeZone','UTC') && ...
        D.intervalEndUTC(end)==datetime(2024,1,1,8,0,0,'TimeZone','UTC') && ...
        strcmp(D.sourceMetadata.canonical_csv_sha256, ...
        '249120565acab4af01f3dab853da075562b809edaf758ff0f7f7033774b33881') && ...
        strcmp(D.sourceMetadata.status,'COMPLETE_WITH_NO_GAPS_OR_DUPLICATES') && ...
        strcmp(D.protocol.TimestampProvenance,'provider_supplied_UTC_interval_start_and_end'), ...
        'Unexpected source identity or timestamp provenance.');
    raw=(9482:43824)';n=numel(raw);expectedTime=D.timeUTC(raw);
    expectedPT=expectedTime;expectedPT.TimeZone='America/Los_Angeles';
    linearNames={'Persistence','SeasonalNaive','Ridge','LASSO','StaticEN','FixedEN05','VAREN'};
    must(isequal(R.ModelNames,linearNames) && isequal(R.RawIndex,raw) && ...
        isequal(R.TimeUTC,expectedTime) && strcmp(R.TimeUTC.TimeZone,'UTC') && ...
        isequal(R.TimeLocal,expectedPT) && strcmp(R.TimeLocal.TimeZone,'America/Los_Angeles') && ...
        isequal(R.TargetMW,D.loadMW(raw)) && isequal(size(R.PredictionMW),[n 7]) && ...
        all(isfinite(R.PredictionMW),'all') && all(R.PredictionMW>0,'all') && ...
        isequal(R.ErrorMW,R.TargetMW-R.PredictionMW),'Linear forecasts are not aligned to the source.');
    must(isequal(LA.InputTimeUTC,D.timeUTC) && isequal(LA.InputLoadMW,D.loadMW) && ...
        isequal(LA.InputIsObserved,D.isObserved) && R.StaticAlpha==1 && ...
        isequal(R.PredictionMW(:,4),R.PredictionMW(:,5)) && LA.Config.W==720 && ...
        LA.Config.Wv==48 && LA.Config.K==5 && LA.Config.CalibrationRows==720 && ...
        LA.Config.AlphaFloor==.001 && LA.Config.FixedAlpha==.5 && numel(LA.PredictorNames)==70, ...
        'Linear calibration, predictors, or input evidence differs.');
    must(isequal(R.PredictionMW(:,1),D.loadMW(raw-1)) && ...
        isequal(R.PredictionMW(:,2),D.loadMW(raw-168)),'Naive forecasts do not reproduce source lags.');
    fields={'ModelNames','RawIndex','TimeUTC','TargetMW','PredictionMW','RuntimeSeconds','StaticAlpha'};
    for j=1:numel(fields),must(isequal(F.linearReference.(fields{j}),R.(fields{j})), ...
        ['Changed saved linear reference: ' fields{j}]);end
    must(strcmp(B.ModelName,'LSBoost24h') && isequal(B.RawIndex,raw) && ...
        isequal(B.TimeUTC,expectedTime) && strcmp(B.TimeUTC.TimeZone,'UTC') && ...
        isequal(B.TimeLocal,expectedPT) && strcmp(B.TimeLocal.TimeZone,'America/Los_Angeles') && ...
        isequal(B.TargetMW,D.loadMW(raw)) && isequal(size(B.PredictionMW),[n 1]) && ...
        all(isfinite(B.PredictionMW)) && all(B.PredictionMW>0) && ...
        isequal(B.ErrorMW,B.TargetMW-B.PredictionMW),'Invalid nonlinear forecasts or timestamps.');
    must(isequal(A.InputTimeUTC,D.timeUTC) && isequal(A.InputLoadMW,D.loadMW) && ...
        isequal(A.InputIsObserved,D.isObserved) && isequal(A.PredictorNames,LA.PredictorNames) && ...
        isequal(A.ForecastTrainingFirstRawIndex,raw-720) && ...
        isequal(A.ForecastTrainingLastRawIndex,raw-1) && ...
        isequal(A.StaticCalibrationRawIndex,(8762:9481)'), 'Nonlinear training/input provenance differs.');
    must(A.Config.W==720 && A.Config.K==5 && A.Config.RetuneEvery==24 && ...
        A.Config.CalibrationRows==720 && A.Config.EvaluationWarmupRows==720 && ...
        A.Config.InitialTrainFraction==.5 && A.Config.RandomSeed==451 && ...
        isequal(A.Config.CycleGrid,[25 50 100 200 400 800 1600]) && ...
        isequal(A.Config.StructureGrid,[3 20;3 5;15 20;15 5]) && B.LearnRate==.1 && ...
        B.SelectedMaxNumSplits==3 && B.SelectedMinLeafSize==20 && B.RetuneEvery==24, ...
        'Frozen nonlinear protocol changed.');
    retuned=mod((0:n-1)',24)==0;held=1+24*floor((0:n-1)'/24);
    must(isequal(B.Retuned,retuned) && sum(B.Retuned)==1431 && ...
        isequal(B.TuningOriginRawIndex,raw(held)) && ...
        isequal(B.NumLearningCycles,B.NumLearningCycles(held)) && ...
        isequal(B.CycleCVScores,B.CycleCVScores(held,:)) && ...
        isequal(B.CycleCVFoldMSE,B.CycleCVFoldMSE(held,:,:)), 'Invalid retuning schedule or held state.');
    must(isequal(size(B.CycleCVScores),[n 7]) && isequal(size(B.CycleCVFoldMSE),[n 5 7]) && ...
        all(isfinite(B.CycleCVScores),'all') && all(B.CycleCVScores>=0,'all') && ...
        all(isfinite(B.CycleCVFoldMSE),'all') && all(B.CycleCVFoldMSE>=0,'all'), ...
        'Invalid chronological tuning losses.');
    near(B.CycleCVScores,squeeze(mean(B.CycleCVFoldMSE,2)),1e-7,'Pooled tuning losses');
    [~,best]=min(B.CycleCVScores,[],2);grid=[25 50 100 200 400 800 1600]';
    must(isequal(B.NumLearningCycles,grid(best)) && B.NumLearningCycles(1)==800 && ...
        isequal(B.CycleAtLowerBoundary,B.NumLearningCycles==25) && ...
        isequal(B.CycleAtUpperBoundary,B.NumLearningCycles==1600),'Invalid chosen tree counts or endpoints.');
    must(isequal(C.A.InputLoadMW,D.loadMW(1:9481)) && ...
        isequal(C.A.InputTimeUTC,D.timeUTC(1:9481)) && strcmp(C.P.Status,'PASS') && ...
        C.P.ForecastOrigins==0 && C.C.SelectedNumLearningCycles==800 && ...
        C.C.SelectedMaxNumSplits==3 && C.C.SelectedMinLeafSize==20,'Calibration prefix or status differs.');
    near(B.CycleCVScores(1,:),C.C.Scores(1,:),1e-7,'First tuning scores');
    near(squeeze(B.CycleCVFoldMSE(1,:,:)),squeeze(C.C.FoldMSE(1,:,:)),1e-7,'First tuning fold losses');
    fields={'PredictionMW','ErrorMW','NumLearningCycles','Retuned','TuningOriginRawIndex', ...
        'CycleCVScores','CycleCVFoldMSE','RawIndex','TargetMW'};
    for j=1:numel(fields)
        name=fields{j};x=B.(name);
        if ndims(x)==3,x=x(1:48,:,:);else,x=x(1:48,:);end
        near(x,H.Br.(name),1e-7,['48-origin reference ' name]);
    end
    must(strcmp(H.Sr.Status,'complete') && H.Sr.CompletedOrigins==48 && ...
        isequal(H.Br.TimeUTC,expectedTime(1:48)),'Reference run or dates differ.');
    must(all(isfinite(R.RuntimeSeconds),'all') && all(R.RuntimeSeconds>=0,'all') && ...
        all(isfinite(B.RuntimeSeconds)) && all(B.RuntimeSeconds>=0) && ...
        all(isfinite(B.CVSeconds)) && all(B.CVSeconds>=0) && all(B.CVSeconds(~retuned)==0) && ...
        all(isfinite(B.FitPredictSeconds)) && all(B.FitPredictSeconds>=0), 'Invalid saved timing arrays.');
end

function [v,u,w,a,calibration]=verifyVolatility(D,A,R)
    z=[NaN;100*diff(log(D.loadMW))];allV=NaN(size(z));
    for t=50:numel(z),allV(t)=var(z(t-48:t-1),0);end
    local=D.timeUTC;local.TimeZone='America/Los_Angeles';cal=year(local)==2019 & isfinite(allV);
    must(sum(cal)==8711,'Unexpected number of complete 2019 volatility windows.');
    lo=min(allV(cal));hi=max(allV(cal));must(isfinite(lo)&&isfinite(hi)&&hi>lo,'Invalid volatility bounds.');
    near([lo hi],[A.VolatilityCalibrationMin A.VolatilityCalibrationMax],1e-9,'Volatility calibration bounds');
    v=allV(R.RawIndex);u=(v-lo)/(hi-lo);w=min(1,max(0,u));a=max(.001,1-w);
    near(v,A.ForecastVolatility,1e-9,'Past-only forecast variance');
    near(u,A.ForecastUnclippedVolatility,1e-9,'Unclipped normalized variance');
    near(w,A.ForecastNormalizedVolatility,1e-9,'Normalized variance');
    near(a,A.ForecastAlpha,1e-9,'Adaptive alpha');near(a,R.Alpha(:,7),1e-9,'Saved VA alpha');
    calibration=struct('Year',2019,'WindowHours',48,'CompleteWindows',sum(cal), ...
        'MinVariance',lo,'MaxVariance',hi,'AlphaFloor',.001);
end

function [labels,masks]=subsetMasks(t)
    h=hour(t);yr=year(t);
    labels={'All','Midday10to14','Evening16to21','Year2020_evaluated','Year2021','Year2022','Year2023'};
    masks={true(numel(t),1),h>=10 & h<=14,h>=16 & h<=21,yr==2020,yr==2021,yr==2022,yr==2023};
end

function T=accuracyTable(y,pred,names,seconds)
    e=y-pred;rmse=sqrt(mean(e.^2,1));r=find(strcmp(names,'StaticEN'),1);
    T=table(names(:),repmat(numel(y),numel(names),1),rmse(:),mean(abs(e),1)', ...
        (100*mean(abs(e)./y,1))',(100*(rmse(r)-rmse)/rmse(r))',sum(seconds,1)', ...
        'VariableNames',{'Model','N','RMSE_MW','MAE_MW','MAPE_pct', ...
        'RMSE_Improvement_vsStaticEN_pct','RecordedForecastLoopSeconds'});
end

function compareAccuracy(new,old,label)
    must(istable(old) && isequal(new.Properties.VariableNames,old.Properties.VariableNames) && ...
        height(new)==height(old) && isequal(string(new.Model),string(old.Model)),[label ' labels differ.']);
    if ismember('Subset',new.Properties.VariableNames)
        must(isequal(string(new.Subset),string(old.Subset)),[label ' subset labels differ.']);
    end
    near(new{:,2:6},old{:,2:6},1e-8,[label ' measures']);
    near(new.RecordedForecastLoopSeconds,old.RecordedForecastLoopSeconds,1e-6,[label ' timing']);
end

function P=primaryTable(T)
    P=T.Effects(T.Effects.HACLag==168,{'PairIndex','ModelA','ModelB','N','HACLag','RMSE_A_MW', ...
