function validateInferenceTables(T,opts,n)
    must(isstruct(T) && all(isfield(T,{'DM','Effects','GW'})) && ...
        istable(T.DM) && istable(T.Effects) && istable(T.GW) && ...
        height(T.DM)==24 && height(T.Effects)==12 && height(T.GW)==24, ...
        'Inference output table geometry differs from the three-pair/four-bandwidth protocol.');
    fields={'DM','Effects','GW'};
    for k=1:numel(fields)
        Q=T.(fields{k});
        must(all(Q.N==n) && all(ismember(Q.PairIndex,1:3)) && ...
            all(ismember(Q.HACLag,opts.HACLags)),['Invalid inference row metadata: ' fields{k}]);
        for p=1:3
            ix=Q.PairIndex==p;
            must(all(strcmp(Q.ModelA(ix),opts.PairNames{p,1})) && ...
                all(strcmp(Q.ModelB(ix),opts.PairNames{p,2})),['Inference pair names differ: ' fields{k}]);
            for L=opts.HACLags
                jx=ix & Q.HACLag==L;
                if strcmp(fields{k},'Effects')
                    must(sum(jx)==1,'A paired-effect row is missing or duplicated.');
                else
                    must(sum(jx)==2 && sum(jx & strcmp(Q.Loss,'MSE'))==1 && ...
                        sum(jx & strcmp(Q.Loss,'MAE'))==1,'A loss-test row is missing or duplicated.');
                end
            end
        end
    end
    must(all(T.DM.HolmFamilySize==3) && all(T.GW.HolmFamilySize==3), ...
        'Holm adjustments must retain all three planned comparison slots.');
    must(all(strlength(string(T.DM.Status))>0) && all(strlength(string(T.GW.Status))>0), ...
        'A loss test has no explicit status.');
    pvalues=[T.DM.P_TwoSided;T.DM.P_Holm;T.GW.P_Joint;T.GW.P_Holm];
    must(all(isnan(pvalues)|(isfinite(pvalues)&pvalues>=0&pvalues<=1)), ...
        'Inference returned an invalid p-value.');
    must(all(isfinite(T.DM.P_TwoSided(strcmp(T.DM.Status,'OK')))) && ...
        all(isfinite(T.GW.P_Joint(strcmp(T.GW.Status,'OK')))), ...
        'A test labeled OK has an undefined p-value.');
end

