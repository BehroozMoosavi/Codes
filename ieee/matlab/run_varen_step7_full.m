function T=accuracyTable(y,prediction,names,seconds)
    e=y-prediction;rmse=sqrt(mean(e.^2,1));
    reference=find(strcmp(names,'StaticEN'),1);
    improvement=100*(rmse(reference)-rmse)/rmse(reference);
    T=table(names(:),repmat(numel(y),numel(names),1),rmse(:), ...
        mean(abs(e),1)',(100*mean(abs(e./y),1))',improvement(:),sum(seconds,1)', ...
        'VariableNames',{'Model','N','RMSE_MW','MAE_MW','MAPE_pct', ...
        'RMSE_Improvement_vsStaticEN_pct','RecordedForecastLoopSeconds'});
end

function T=numberDifference(x,y,tolerance,label)
    must(isequal(size(x),size(y)),['Shape mismatch: ' label]);
    must(all(isfinite(x(:))) && all(isfinite(y(:))),['Non-finite comparison: ' label]);
    difference=max(abs(double(x(:))-double(y(:))));
    if isempty(difference),difference=0;end
    T=table({label},difference,tolerance,difference<=tolerance, ...
        'VariableNames',{'Quantity','MaxAbsoluteDifference','AbsoluteTolerance','Passed'});
    must(difference<=tolerance,sprintf('%s differs by %.17g, tolerance %.17g.',label,difference,tolerance));
end

function [folder,file]=resolveStep5(location)
    location=char(location);
    if isfolder(location)
        folder=location;file=fullfile(folder,'full','varen_corrected_results.mat');
    else
        [parent,name,ext]=fileparts(location);[folder,last]=fileparts(parent);
        must(strcmp([name ext],'varen_corrected_results.mat') && strcmp(last,'full'), ...
            'Select full/varen_corrected_results.mat from the completed Step 5 run.');
        file=location;
    end
    must(isfile(file) && isfile(fullfile(folder,'step5_inputs.mat')) && ...
        isfile(fullfile(folder,'step5_summary.txt')),'The completed Step 5 folder is incomplete.');
    must(contains(fileread(fullfile(folder,'step5_summary.txt')),'STEP5_STATUS: PASS'), ...
        'The selected Step 5 run has not reported PASS.');
end

