function [runDir,zipPath] = run_varen_step7_full(step5Location,step6bLocation)
%RUN_VAREN_STEP7_FULL Check resume, then evaluate the LSBoost24h benchmark.
%
% NEW: [step7Folder,step7Zip] = run_varen_step7_full(step5Folder,step6bFolder)
% NEW: [step7Folder,step7Zip] = run_varen_step7_full() % two file pickers
% RESUME: run_varen_step7_full('/path/to/existing/step7_full_...')
%
% Revision 1.0. Source-reviewed; no MATLAB execution is claimed here.
% Built-in MATLAB gates must pass before the long evaluation starts.
%
% Frozen computational-budget policy:
%   Initial structure and learning rate come from Step 6b calibration.
%   Retain the full count grid [25 50 100 200 400 800 1600].
%   Retune count at origins 1,25,49,... using the preceding 720 hours and
%   five chronological folds. Refit the chosen model EVERY hour on the
%   latest 720 hours. The tuning interval is 24 elapsed hours across DST.
%   This differs from the hourly tuning in Step 6 and the linear models.
%   The decision uses calibration cost, not evaluation forecast errors.
%
% Preflight: independently reproduce the first forecast with the original
% user-tested varen_lsboost_core; compare 48 uninterrupted origins with a
% 12-origin pause and resume to 48; check target/future independence.
% Then run all 34343 origins, saving checkpoints every 250 completed rows.
% Use one MATLAB session per run folder and keep source/settings unchanged.

    corePath = which('varen_lsboost_checkpointed_core');
    must(~isempty(corePath) && exist('varen_lsboost_checkpointed_core','file')==2, ...
        'Put varen_lsboost_checkpointed_core.m beside this wrapper.');
    wrapperPath = [mfilename('fullpath') '.m'];
    coreSource = fileread(corePath);
    resumeRun = nargin==1 && isfolder(step5Location) && ...
        isfile(fullfile(step5Location,'step7_inputs.mat'));
    if resumeRun
        runDir = char(step5Location);
        I = load(fullfile(runDir,'step7_inputs.mat'));
        must(strcmp(I.coreSourceAtStart,coreSource), ...
            'The checkpoint core changed. Restore the source used for this run.');
        D=I.D; linear=I.linear; calibration=I.calibration;
        inputPaths=I.inputPaths; originalCoreSourceAtStart=I.originalCoreSourceAtStart;
    else
        if nargin<1 || isempty(step5Location)
            step5Location=chooseMat('Select full/varen_corrected_results.mat from completed Step 5');
        end
        if nargin<2 || isempty(step6bLocation)
            step6bLocation=chooseMat('Select step6b_calibration_results.mat');
        end
        [step5Folder,linearFile]=resolveStep5(step5Location);
        if isfolder(step6bLocation)
            calibrationFile=fullfile(char(step6bLocation),'step6b_calibration_results.mat');
        else
            calibrationFile=char(step6bLocation);
        end
        must(isfile(calibrationFile),'Step 6b calibration MAT was not found.');
        J=load(fullfile(step5Folder,'step5_inputs.mat'),'D'); D=J.D;
        linear=load(linearFile,'R','A');
        calibration=load(calibrationFile,'C','A','P','sourceProtocol','sourceMetadata');
        validateInputs(D,linear,calibration);
        originalCorePath=which('varen_lsboost_core');
        must(~isempty(originalCorePath) && exist('varen_lsboost_core','file')==2, ...
            'Keep the original tested varen_lsboost_core.m in the MATLAB folder for the reference gate.');
        originalCoreSourceAtStart=fileread(originalCorePath);
        inputPaths=struct('Step5Folder',step5Folder,'Step5Results',linearFile, ...
            'Step6bResults',calibrationFile,'OriginalCore',originalCorePath);
        baseDir=fileparts(wrapperPath);
        [~,name]=fileparts(tempname(baseDir));
        runDir=fullfile(baseDir,['step7_full_' name]);
        [ok,msg]=mkdir(runDir);
        if ~ok,error('VAREN:Step7Folder','Cannot create run folder: %s',msg);end
        coreSourceAtStart=coreSource;
        save(fullfile(runDir,'step7_inputs.mat'),'D','linear','calibration', ...
            'inputPaths','coreSourceAtStart','originalCoreSourceAtStart','-v7.3');
        copyfile(wrapperPath,fullfile(runDir,'run_varen_step7_full.m'));
        copyfile(corePath,fullfile(runDir,'varen_lsboost_checkpointed_core.m'));
        copyfile(originalCorePath,fullfile(runDir,'varen_lsboost_core.m'));
    end

    zipPath=fullfile(runDir,'step7_full_results.zip');
    oldDiaryFile=get(0,'DiaryFile'); oldDiaryState=get(0,'Diary');
    diaryCleanup=onCleanup(@()restoreDiary(oldDiaryFile,oldDiaryState)); %#ok<NASGU>
    diary(fullfile(runDir,'step7_console.txt'));
    try
        fprintf('\nVA-REN REVISION: STEP 7 FULL NONLINEAR EVALUATION\nRevision 1.0; MATLAB %s\n',version);
        fprintf('Existing run resumed: %d\nRun folder: %s\n',resumeRun,runDir);
        fprintf('Model: LSBoost24h. Count tuning every 24 elapsed origins; model refitting every hour.\n');
        fprintf('All seven tree-count candidates retained. This tuning policy differs from hourly EN tuning.\n');
        fprintf('Calibration structure: 3 splits, minimum leaf 20, learning rate .1.\n');
        fprintf('Initial count: 800. Later counts use past-only scheduled tuning.\n');
        validateInputs(D,linear,calibration);
        opts=struct('IsObserved',D.isObserved,'MaxForecasts',48,'Verbose',true, ...
            'OutputDir',fullfile(runDir,'resume_check'));
        gatePath=fullfile(runDir,'step7_equivalence_check.mat');
        if isfile(gatePath)
            H=load(gatePath,'G'); G=H.G;
            must(strcmp(G.Status,'PASS') && strcmp(G.CoreSource,coreSource) && ...
                strcmp(G.OriginalCoreSource,originalCoreSourceAtStart) && ...
                strcmp(G.MATLABVersion,version), ...
                'The retained preflight does not match this source or MATLAB version.');
            fprintf('Prior MATLAB preflight PASS retained.\n');
        else
            originalCorePath=which('varen_lsboost_core');
            must(~isempty(originalCorePath) && ...
                strcmp(fileread(originalCorePath),originalCoreSourceAtStart), ...
                'The original LSBoost reference core changed or is missing.');
            originalPath=fullfile(runDir,'step7_original_reference.mat');
            if isfile(originalPath)
                H=load(originalPath,'Bo','Ao','ReferenceSeconds');
                Bo=H.Bo; Ao=H.Ao; referenceSeconds=H.ReferenceSeconds;
            else
                fprintf('\nPreflight 1: independently reproduce the first forecast and expanded calibration.\n');
                originalOpts=struct('IsObserved',D.isObserved,'MaxForecasts',1, ...
                    'CycleGrid',[25 50 100 200 400 800 1600],'Verbose',true);
                tick=tic; [Bo,Ao]=varen_lsboost_core(D.timeUTC,D.loadMW,originalOpts);
                referenceSeconds=toc(tick);
                ReferenceSeconds=referenceSeconds; %#ok<NASGU>
                save(originalPath,'Bo','Ao','ReferenceSeconds','-v7.3');
            end
            numberDifference(Bo.CalibrationFoldMSE,calibration.C.FoldMSE,1e-7, ...
                'Original core calibration fold losses');
            numberDifference(Bo.CalibrationTable.CV_MSE_MW2, ...
                calibration.C.CalibrationTable.CV_MSE_MW2,1e-7,'Original core calibration scores');
            must(Bo.SelectedMaxNumSplits==3 && Bo.SelectedMinLeafSize==20 && ...
                Bo.NumLearningCycles==800 && Ao.PrefixCheck.Pass, ...
                'The original core did not reproduce the calibrated structure/count.');

            reference48Path=fullfile(runDir,'step7_reference48.mat');
            if isfile(reference48Path)
                H=load(reference48Path,'Br','Ar','Sr'); Br=H.Br;Ar=H.Ar;Sr=H.Sr;
            else
                fprintf('\nPreflight 2: 48 uninterrupted origins with the frozen 24-hour tuning policy.\n');
                control=struct('WriteCheckpoints',false,'CheckpointEvery',12,'StopAfter',Inf);
                rngBefore=rng;
                [Br,Ar,Sr]=varen_lsboost_checkpointed_core(D.timeUTC,D.loadMW,calibration,opts,control);
                rngAfter=rng; must(isequal(rngBefore,rngAfter),'Reference run did not restore RNG.');
                validateOutput(D,calibration,Br,Ar,48);
                save(reference48Path,'Br','Ar','Sr','-v7.3');
            end
            validateOutput(D,calibration,Br,Ar,48);
            comparisons=numberDifference(Bo.PredictionMW,Br.PredictionMW(1),1e-7, ...
                'First forecast against original core');
            comparisons=[comparisons;numberDifference(Bo.CycleCVScores,Br.CycleCVScores(1,:),1e-7, ...
                'First tuning scores against original core')];
            comparisons=[comparisons;numberDifference(Bo.NumLearningCycles,Br.NumLearningCycles(1),0, ...
                'First count against original core')];

            fprintf('\nPreflight 3: pause after 12 origins, then resume to 48 across the second tuning event.\n');
            phasePath=fullfile(runDir,'step7_resume_phase1.mat');
            if isfile(phasePath)
                H=load(phasePath,'phase1','prefix');phase1=H.phase1;prefix=H.prefix;
            else
                control=struct('WriteCheckpoints',true,'CheckpointEvery',12,'StopAfter',12);
                [~,~,phase1]=varen_lsboost_checkpointed_core(D.timeUTC,D.loadMW,calibration,opts,control);
                must(strcmp(phase1.Status,'paused') && phase1.CompletedOrigins==12, ...
                    'Checkpoint test did not pause after 12 complete origins.');
                H=load(phase1.CheckpointFile,'checkpoint');
                prefix=struct('PredictionMW',H.checkpoint.PredictionMW, ...
                    'RuntimeSeconds',H.checkpoint.RuntimeSeconds, ...
                    'NumLearningCycles',H.checkpoint.NumLearningCycles, ...
                    'TuningOriginRawIndex',H.checkpoint.TuningOriginRawIndex);
                save(phasePath,'phase1','prefix','-v7');
            end
            control=struct('WriteCheckpoints',true,'CheckpointEvery',12,'StopAfter',Inf);
            [Bp,Ap,Sp]=varen_lsboost_checkpointed_core(D.timeUTC,D.loadMW,calibration,opts,control);
            must(Sp.Resumed && Sp.StartedFromCompletedOrigins>=12 && ...
                Sp.CompletedOrigins==48 && strcmp(Sp.Status,'complete'), ...
                'The continuation did not complete using the saved checkpoint.');
            validateOutput(D,calibration,Bp,Ap,48);
            fields={'PredictionMW','ErrorMW','NumLearningCycles','Retuned','TuningOriginRawIndex', ...
                'CycleCVScores','CycleCVFoldMSE'};
            tolerances=[1e-7 1e-7 0 0 0 1e-7 1e-7];
            for j=1:numel(fields)
                comparisons=[comparisons;numberDifference(Br.(fields{j}),Bp.(fields{j}), ...
                    tolerances(j),['Resume ' fields{j}])]; %#ok<AGROW>
            end
            comparisons=[comparisons;numberDifference(prefix.PredictionMW,Bp.PredictionMW(1:12),0, ...
                'Retained prefix predictions'); ...
                numberDifference(prefix.RuntimeSeconds,Bp.RuntimeSeconds(1:12),0,'Retained prefix runtimes'); ...
                numberDifference(prefix.NumLearningCycles,Bp.NumLearningCycles(1:12),0,'Retained prefix counts'); ...
                numberDifference(prefix.TuningOriginRawIndex,Bp.TuningOriginRawIndex(1:12),0,'Retained tuning origin')];

            fprintf('\nPreflight 4: change the first target and later loads; require the first forecast to stay unchanged.\n');
            changedLoad=D.loadMW;
            future=(9482:numel(changedLoad))';
            changedLoad(future)=changedLoad(future).*exp(.05*cos((0:numel(future)-1)'));
            checkOpts=opts;checkOpts.MaxForecasts=1;checkOpts.Verbose=false;
            control=struct('WriteCheckpoints',false,'CheckpointEvery',12,'StopAfter',Inf);
            tick=tic;
            [Bf,Af,~]=varen_lsboost_checkpointed_core(D.timeUTC,changedLoad,calibration,checkOpts,control);
            futureCheckSeconds=toc(tick);
            must(Bf.TargetMW~=Br.TargetMW(1),'Future perturbation did not change the target.');
            comparisons=[comparisons;numberDifference(Br.PredictionMW(1),Bf.PredictionMW,1e-7, ...
                'Future perturbation forecast'); ...
                numberDifference(Br.CycleCVScores(1,:),Bf.CycleCVScores,1e-7,'Future perturbation tuning'); ...
                numberDifference(Br.NumLearningCycles(1),Bf.NumLearningCycles,0,'Future perturbation count')];
            must(Af.CalibrationReproductionMaxMSE<=1e-7, ...
                'Perturbed run did not reproduce historical calibration.');
            must(strcmp(coreSource,fileread(corePath)) && ...
                strcmp(originalCoreSourceAtStart,fileread(originalCorePath)), ...
                'A source file changed during the preflight.');
            meanCV=mean(Br.CVSeconds(Br.Retuned));
            meanFit=mean(Br.FitPredictSeconds);
            meanOther=mean(max(0,Br.RuntimeSeconds-Br.CVSeconds-Br.FitPredictSeconds));
            estimateHours=(1431*meanCV+34343*(meanFit+meanOther))/3600;
            G=struct('Status','PASS','MATLABVersion',version,'CoreSource',coreSource, ...
                'OriginalCoreSource',originalCoreSourceAtStart,'Comparisons',comparisons, ...
                'PreflightOrigins',48,'PauseAfterOrigins',12,'PreflightRetunes',2, ...
                'ExpectedFullRetunes',1431,'RoughFullFittingHours',estimateHours, ...
                'MeanRetuneCVSeconds',meanCV,'MeanHourlyFitPredictSeconds',meanFit, ...
                'OriginalReferenceSeconds',referenceSeconds, ...
                'FuturePerturbationSeconds',futureCheckSeconds,'ResumeState',Sp);
            writetable(comparisons,fullfile(runDir,'step7_equivalence_checks.csv'));
            save(gatePath,'G','-v7.3');
            fprintf('CHECKPOINT_EQUIVALENCE: PASS (48 reference; 12 paused then resumed to 48).\n');
            fprintf('ORIGINAL_CORE_REFERENCE: PASS\nFUTURE_PERTURBATION_CHECK: PASS\n');
        end

        fprintf('\nStarting/continuing all 34343 common forecast origins.\n');
        fprintf('Count tuning events: 1431; hourly refits: 34343.\n');
        fprintf('48-origin preflight planning estimate: %.2f hours of fitting.\n',G.RoughFullFittingHours);
        fprintf('Estimate excludes checkpoint/output costs, pauses, and later variation in counts or solver cost.\n');
        fprintf('Checkpoints save every 250 completed origins.\n');
        fprintf('Resume with: run_varen_step7_full(''%s'')\n\n',runDir);
        opts.OutputDir=fullfile(runDir,'full');opts.MaxForecasts=Inf;
        control=struct('WriteCheckpoints',true,'CheckpointEvery',250,'StopAfter',Inf);
        callClock=tic;
        [B,A,S]=varen_lsboost_checkpointed_core(D.timeUTC,D.loadMW,calibration,opts,control);
        fullCallWallSeconds=toc(callClock);
        must(strcmp(S.Status,'complete') && S.CompletedOrigins==34343,'Full nonlinear run is incomplete.');
        validateOutput(D,calibration,B,A,34343);
        H=load(fullfile(runDir,'step7_reference48.mat'),'Br');
        numberDifference(B.PredictionMW(1:48),H.Br.PredictionMW,1e-7,'Full prefix against preflight');
        numberDifference(B.NumLearningCycles(1:48),H.Br.NumLearningCycles,0,'Full prefix counts');
        numberDifference(B.CycleCVScores(1:48,:),H.Br.CycleCVScores,1e-7,'Full prefix tuning scores');
        [metrics,subsetMetrics,parameters,timing,endpoints]=writeResults(runDir,D,linear,calibration,B,A,S,G);
        save(fullfile(runDir,'step7_execution_state.mat'),'S','fullCallWallSeconds','-v7');
        summary=sprintf([ ...
            'VA-REN REVISION: STEP 7 FULL NONLINEAR EVALUATION\nRevision 1.0; MATLAB %s\n\n' ...
            'STEP7_STATUS: PASS\nCHECKPOINT_EQUIVALENCE: PASS\n' ...
            'ORIGINAL_CORE_REFERENCE: PASS\nFUTURE_PERTURBATION_CHECK: PASS\n' ...
            'FULL_PERIOD_NONLINEAR_FORECASTS_RUN: YES\nFORECAST_ORIGINS: 34343\n' ...
            'NONLINEAR_MODEL: LSBoost24h\nTUNING_EVENTS: 1431\nHOURLY_REFITS: 34343\n\n' ...
            'First forecast interval start: %s\nLast forecast interval start: %s\n' ...
            'Fixed structure: max splits 3; minimum leaf 20; learning rate .1.\n' ...
            'Count grid: 25, 50, 100, 200, 400, 800, 1600.\n' ...
            'Count retuned every 24 elapsed origins; model refitted every hour on latest 720 hours.\n' ...
            'This differs from hourly lambda tuning in Step 5 and hourly count tuning in Step 6.\n' ...
            'The frequency decision was based on calibration cost, not evaluation accuracy.\n\n' ...
            'Prior Step 6b calibration: %.3f seconds (already incurred, not rerun in full loop).\n' ...
            'Full-loop chronological tuning time: %.3f seconds\n' ...
            'Full-loop hourly fit/predict time: %.3f seconds\n' ...
            'Total recorded nonlinear forecast-loop time: %.3f seconds (%.3f hours)\n' ...
            'Core cumulative compute time: %.3f seconds\nLatest full-core invocation wall time: %.3f seconds\n' ...
            'Latest invocation resumed from %d origins and computed %d additional origins.\n' ...
            'Latest invocation checkpoint write/read time: %.3f / %.3f seconds\n' ...
            'Paused time and preflight checks are outside full-loop timings.\n' ...
            'A crash can leave work after the last saved origin unrecorded.\n\n' ...
            'Endpoint rates are reported separately for tuning events and hours using the selected count.\n' ...
            'Eight aligned outputs include the seven saved Step 5 outputs; StaticEN and LASSO coincide.\n' ...
            'Step 5 models are reused without refitting. Combined timings come from separate runs.\n' ...
            'Target: hourly system demand, not solar-subtracted net load.\n' ...
            'Published historical actuals may be revised; completed-hour availability is assumed.\n' ...
            'Annual lag: 8760 elapsed hours. Calendar predictors: America/Los_Angeles.\n' ...
            'No significance tests are performed by this script. A valid run does not establish superiority.\n' ...
            'Return step7_full_results.zip.\n'],version,char(utcText(B.TimeUTC(1))), ...
            char(utcText(B.TimeUTC(end))),calibration.C.CalibrationSeconds, ...
            sum(B.CVSeconds),sum(B.FitPredictSeconds),sum(B.RuntimeSeconds),sum(B.RuntimeSeconds)/3600, ...
            B.TotalSeconds,fullCallWallSeconds,S.StartedFromCompletedOrigins,S.OriginsComputedThisCall, ...
            S.CurrentCallCheckpointSeconds,S.CurrentCallResumeReadSeconds);
        writeText(fullfile(runDir,'step7_summary.txt'),summary);
        fprintf('\n%s\n',summary);disp(metrics);disp(endpoints);
        diary('off');packageResults(runDir,zipPath,false);
        fprintf('Upload ZIP: %s\n',zipPath);
    catch ME
        report=getReport(ME,'extended','hyperlinks','off');
        fprintf('\nSTEP7_STATUS: FAIL\n%s\nRun folder retained: %s\n',report,runDir);
        try
            writeText(fullfile(runDir,'step7_summary.txt'),sprintf([ ...
                'STEP7_STATUS: FAIL\nCompleted-origin checkpoints remain in this folder.\n' ...
                'Preserve the error for review; do not change settings or suppress a fitting warning.\n\n%s\n'],report));
            diary('off');failureZip=fullfile(runDir,'step7_failure.zip');
            packageResults(runDir,failureZip,true);
            fprintf('Upload failure ZIP: %s\n',failureZip);
        catch packagingError
            diary('off');fprintf('Failure ZIP could not be created: %s\n',packagingError.message);
            fprintf('Return the complete error and step7_console.txt.\n');
        end
        rethrow(ME);
    end
end

function validateInputs(D,L,C)
    must(all(isfield(D,{'timeUTC','intervalEndUTC','loadMW','isObserved','protocol','sourceMetadata'})) && ...
        all(isfield(L,{'R','A'})) && all(isfield(C,{'C','A','P','sourceMetadata'})), ...
        'Missing source, linear-result or calibration variables.');
    must(isdatetime(D.timeUTC) && ~isempty(D.timeUTC.TimeZone) && ...
        isdatetime(D.intervalEndUTC) && ~isempty(D.intervalEndUTC.TimeZone) && ...
        iscolumn(D.timeUTC) && iscolumn(D.intervalEndUTC) && ...
        iscolumn(D.loadMW) && iscolumn(D.isObserved) && numel(D.timeUTC)==43824 && ...
        numel(D.intervalEndUTC)==43824 && numel(D.loadMW)==43824 && numel(D.isObserved)==43824 && ...
        ~any(isnat(D.timeUTC)) && ~any(isnat(D.intervalEndUTC)) && ...
        all(diff(D.timeUTC)==hours(1)) && all(D.intervalEndUTC-D.timeUTC==hours(1)) && ...
        isreal(D.loadMW) && all(isfinite(D.loadMW)) && all(D.loadMW>0) && ...
        islogical(D.isObserved) && all(D.isObserved),'Invalid frozen hourly source arrays.');
    must(D.timeUTC(1)==datetime(2019,1,1,8,0,0,'TimeZone','UTC') && ...
        D.intervalEndUTC(end)==datetime(2024,1,1,8,0,0,'TimeZone','UTC') && ...
        strcmp(D.sourceMetadata.canonical_csv_sha256, ...
        '249120565acab4af01f3dab853da075562b809edaf758ff0f7f7033774b33881') && ...
        strcmp(D.sourceMetadata.status,'COMPLETE_WITH_NO_GAPS_OR_DUPLICATES') && ...
        D.protocol.ExpectedForecasts==34343 && ...
        strcmp(D.protocol.TimestampProvenance,'provider_supplied_UTC_interval_start_and_end'), ...
        'Unexpected source identity or timestamp provenance.');
    R=L.R;A=L.A;
    names={'Persistence','SeasonalNaive','Ridge','LASSO','StaticEN','FixedEN05','VAREN'};
    must(isequal(R.ModelNames,names) && isequal(R.RawIndex,(9482:43824)') && ...
        isequal(size(R.PredictionMW),[34343 7]) && ...
        all(isfinite(R.PredictionMW),'all') && all(R.PredictionMW>0,'all') && ...
        isequal(R.TargetMW,D.loadMW(R.RawIndex)) && isequal(R.TimeUTC,D.timeUTC(R.RawIndex)) && ...
        isequal(R.ErrorMW,R.TargetMW-R.PredictionMW) && ...
        isequal(A.InputLoadMW,D.loadMW) && isequal(A.InputTimeUTC,D.timeUTC) && ...
        isequal(A.InputIsObserved,D.isObserved),'The Step 5 forecasts are not aligned to this source.');
    must(R.StaticAlpha==1 && isequal(R.PredictionMW(:,4),R.PredictionMW(:,5)) && ...
        A.Config.W==720 && A.Config.K==5 && A.Config.CalibrationRows==720 && ...
        A.Config.InitialTrainFraction==.5 && numel(A.PredictorNames)==70, ...
        'Unexpected Step 5 calibration or training protocol.');
    must(strcmp(C.P.Status,'PASS') && C.P.ForecastOrigins==0 && ...
        strcmp(C.sourceMetadata.canonical_csv_sha256,D.sourceMetadata.canonical_csv_sha256) && ...
        isequal(C.A.InputTimeUTC,D.timeUTC(1:9481)) && ...
        isequal(C.A.InputLoadMW,D.loadMW(1:9481)) && ...
        isequal(C.A.InputIsObserved,D.isObserved(1:9481)) && ...
        isequal(C.A.CalibrationRawIndex,(8762:9481)') && ...
        isequal(C.A.PredictorNames,A.PredictorNames),'Step 6b calibration does not match the source prefix.');
    must(strcmp(C.A.MATLABVersion,version) && ...
        C.C.SelectedMaxNumSplits==3 && C.C.SelectedMinLeafSize==20 && ...
        C.C.SelectedStructureIndex==1 && C.C.SelectedNumLearningCycles==800 && ...
        C.C.LearnRate==.1 && isequal(C.A.Config.CycleGrid,[25 50 100 200 400 800 1600]) && ...
        isequal(C.A.Config.StructureGrid,[3 20;3 5;15 20;15 5]) && ...
        C.A.Config.RandomSeed==451 && C.A.PrefixCheck.Pass, ...
        'Use the reviewed Step 6b calibration and the same MATLAB version.');
end

function validateOutput(D,C,B,A,n)
    rows=(9482:9482+n-1)';
    expectedRetune=mod((0:n-1)',24)==0;
    lastRetune=1+24*floor((0:n-1)'/24);
    must(strcmp(B.ModelName,'LSBoost24h') && B.RetuneEvery==24 && ...
        isequal(B.RawIndex,rows) && isequal(B.TimeUTC,D.timeUTC(rows)) && ...
        isequal(B.TargetMW,D.loadMW(rows)) && isequal(size(B.PredictionMW),[n 1]) && ...
        all(isfinite(B.PredictionMW)) && all(B.PredictionMW>0) && ...
        isequal(B.ErrorMW,B.TargetMW-B.PredictionMW),'Invalid nonlinear origins, targets or predictions.');
    must(isequal(A.InputTimeUTC,D.timeUTC) && isequal(A.InputLoadMW,D.loadMW) && ...
        isequal(A.InputIsObserved,D.isObserved) && ...
        isequal(A.PredictorNames,C.A.PredictorNames) && ...
        isequal(A.StaticCalibrationRawIndex,(8762:9481)') && ...
        A.StaticCalibrationEndUTC<B.TimeUTC(1) && ...
        isequal(A.ForecastTrainingFirstRawIndex,rows-720) && ...
        isequal(A.ForecastTrainingLastRawIndex,rows-1),'Input or fitting-window provenance changed.');
    must(isequal(B.Retuned,expectedRetune) && sum(B.Retuned)==ceil(n/24) && ...
        isequal(B.TuningOriginRawIndex,rows(lastRetune)) && ...
        isequal(B.NumLearningCycles,B.NumLearningCycles(lastRetune)) && ...
        isequal(B.CycleCVScores,B.CycleCVScores(lastRetune,:)) && ...
        isequal(B.CycleCVFoldMSE,B.CycleCVFoldMSE(lastRetune,:,:)), ...
        'Retuning schedule or retained count/validation scores are inconsistent.');
    must(isequal(size(B.CycleCVScores),[n 7]) && ...
        isequal(size(B.CycleCVFoldMSE),[n 5 7]) && ...
        all(isfinite(B.CycleCVScores),'all') && all(B.CycleCVScores>=0,'all') && ...
        all(isfinite(B.CycleCVFoldMSE),'all') && all(B.CycleCVFoldMSE>=0,'all'), ...
        'Invalid stored chronological tuning losses.');
    [~,chosen]=min(B.CycleCVScores,[],2);
    grid=[25 50 100 200 400 800 1600]';
    must(isequal(B.NumLearningCycles,grid(chosen)) && ...
        isequal(B.CycleAtLowerBoundary,B.NumLearningCycles==25) && ...
        isequal(B.CycleAtUpperBoundary,B.NumLearningCycles==1600) && ...
        B.NumLearningCycles(1)==800 && B.SelectedMaxNumSplits==3 && ...
        B.SelectedMinLeafSize==20 && B.LearnRate==.1, ...
        'Selected tree counts, structure or endpoint flags changed.');
    must(all(isfinite(B.RuntimeSeconds)) && all(B.RuntimeSeconds>=0) && ...
        all(isfinite(B.CVSeconds)) && all(B.CVSeconds>=0) && ...
        all(B.CVSeconds(~B.Retuned)==0) && ...
        all(isfinite(B.FitPredictSeconds)) && all(B.FitPredictSeconds>=0), ...
        'Invalid or incorrectly attributed tuning/refitting time.');
    must(A.CalibrationReproductionMaxMSE<=1e-7 && ...
        A.CalibrationReproductionMaxFoldMSE<=1e-7, ...
        'First scheduled tuning failed to reproduce Step 6b calibration.');
    numberDifference(B.CycleCVScores(1,:),C.C.Scores(1,:),1e-7,'First scheduled tuning scores');
    numberDifference(squeeze(B.CycleCVFoldMSE(1,:,:)), ...
        squeeze(C.C.FoldMSE(1,:,:)),1e-7,'First scheduled tuning fold losses');
end

