    fprintf(fid,'%s',value);
end

function packageResults(folder,zipPath,includeCheckpoints)
    listing=dir(folder);listing=listing(~[listing.isdir]);names={listing.name};
    names=names(~startsWith(names,'.') & ~endsWith(names,'.zip'));
    if includeCheckpoints
        directories={'full','resume_check'};
        checkpoints={'lsboost_checkpoint.mat','lsboost_checkpoint_previous.mat'};
        for j=1:numel(directories)
            for k=1:numel(checkpoints)
                name=fullfile(directories{j},checkpoints{k});
                if isfile(fullfile(folder,name)),names{end+1}=name;end %#ok<AGROW>
            end
        end
    end
    zip(zipPath,names,folder);
end

