function [reportDir, zipPath] = run_varen_step6_nonlinear_pilot(step5Location)
%RUN_VAREN_STEP6_NONLINEAR_PILOT Validate a 24-origin LSBoost benchmark.
%
% [step6Folder,step6Zip] = run_varen_step6_nonlinear_pilot(step5Folder)
% [step6Folder,step6Zip] = run_varen_step6_nonlinear_pilot() % file picker
%
% Supply the COMPLETED Step 5 run folder, or its full/varen_corrected_results.mat.
% This wrapper reads the saved inputs and forecasts. It does not refit or
% overwrite any Step 5 model. A fresh step6_nonlinear_pilot_* folder receives
% the diagnostics, source snapshots and upload ZIP.
%
% Revision 1.0. Source-reviewed against MATLAB R2025a documentation. MATLAB
% execution is the next validation step; no execution is claimed here.
%
% Protocol fixed before seeing LSBoost forecast errors:
%   Same 70 predictors, log-change response, 720-hour histories and origins.
%   Initial 720 rows choose tree structure using five chronological folds.
%   Learning rate .1; (max splits,min leaf)=[3,20;3,5;15,20;15,5].
%   At each origin, five chronological folds choose 25/50/100/200 trees.
%   Every fit and validation loss uses only data available at that origin.
%   Pilot errors are diagnostics, never a basis for tuning the benchmark.
%
% Built-in checks cover common targets, feature names, train/validation
% ordering, staged-tree prediction equivalence, target/future perturbation,
% RNG restoration, cycle selection and output integrity.
% No full nonlinear evaluation or significance tests are performed.

    if nargin < 1 || isempty(step5Location)
        [f,p] = uigetfile('*.mat', ...
            'Select full/varen_corrected_results.mat from the completed Step 5');
        if isequal(f,0)
            error('VAREN:Step6Cancelled','No Step 5 full-results MAT was selected.');
        end
        step5Location = fullfile(p,f);
    end
    [step5Folder,referenceFile] = resolveStep5(step5Location);
    corePath = which('varen_lsboost_core');
    require(~isempty(corePath) && exist('varen_lsboost_core','file')==2, ...
        'Put varen_lsboost_core.m in the same MATLAB folder as this wrapper.');
    require(exist('fitrensemble','file')==2 && exist('templateTree','file')==2, ...
        'Statistics and Machine Learning Toolbox fitrensemble/templateTree are required.');

    wrapperPath = [mfilename('fullpath') '.m'];
    baseDir = fileparts(wrapperPath);
    [~,uniqueName] = fileparts(tempname(baseDir));
    reportDir = fullfile(baseDir,['step6_nonlinear_pilot_' uniqueName]);
    [ok,msg] = mkdir(reportDir);
    if ~ok, error('VAREN:Step6Folder','Cannot create output folder: %s',msg); end
    zipPath = fullfile(reportDir,'step6_nonlinear_pilot_results.zip');
    oldDiaryFile = get(0,'DiaryFile');
    oldDiaryState = get(0,'Diary');
    diaryCleanup = onCleanup(@()restoreDiary(oldDiaryFile,oldDiaryState)); %#ok<NASGU>
    diary(fullfile(reportDir,'step6_console.txt'));

    try
        fprintf('\nVA-REN REVISION: STEP 6 NONLINEAR BENCHMARK PILOT\n');
        fprintf('Revision 1.0; MATLAB %s\n',version);
        fprintf('Step 5 folder: %s\nOutput folder: %s\n',step5Folder,reportDir);
        copyfile(wrapperPath,fullfile(reportDir,'run_varen_step6_nonlinear_pilot.m'));
        copyfile(corePath,fullfile(reportDir,'varen_lsboost_core.m'));
        sourceSnapshot = fileread(corePath);
        S = load(fullfile(step5Folder,'step5_inputs.mat'),'D');
        Q = load(referenceFile,'R','A');
        require(isfield(S,'D') && all(isfield(Q,{'R','A'})), ...
            'Missing saved Step 5 inputs or results.');
        D = S.D;
        reference = Q.R;
        linearAudit = Q.A;
        validateReference(D,reference,linearAudit,step5Folder);

        opts = struct('IsObserved',D.isObserved,'MaxForecasts',24,'Verbose',true);
        sourceProtocol = D.protocol;
        sourceMetadata = D.sourceMetadata;
        startedUTC = datetime('now','TimeZone','UTC');
        save(fullfile(reportDir,'step6_run_metadata.mat'), ...
            'step5Folder','referenceFile','corePath','sourceSnapshot','opts', ...
            'sourceProtocol','sourceMetadata','startedUTC','-v7');
        fprintf('\n24 origins; one additional model: MATLAB LSBoost regression trees.\n');
        fprintf('720-hour histories; the same 70 predictors and five chronological folds.\n');
        fprintf('Initial structure calibration; rolling choice of 25, 50, 100 or 200 trees.\n');
        fprintf('Step 5 regressions are reused. No full nonlinear run is started.\n');
        fprintf('The pilot also checks staged predictions and future-target independence.\n\n');

        rngBefore = rng;
        pilotClock = tic;
        [B,A] = varen_lsboost_core(D.timeUTC,D.loadMW,opts);
        coreCallSeconds = toc(pilotClock);
        rngAfter = rng;
        require(isequal(rngBefore,rngAfter),'Core did not restore the caller RNG state.');
        validatePilot(D,reference,linearAudit,B,A);

        fprintf('\nChecking that the first forecast does not depend on its target or later loads.\n');
        changedLoad = D.loadMW;
        firstRaw = B.RawIndex(1);
        futureRows = (firstRaw:numel(changedLoad))';
        changedLoad(futureRows) = changedLoad(futureRows).* ...
            exp(0.05*cos((0:numel(futureRows)-1)'));
        checkOpts = opts;
        checkOpts.MaxForecasts = 1;
        checkOpts.Verbose = false;
        checkClock = tic;
        [Bcheck,Acheck] = varen_lsboost_core(D.timeUTC,changedLoad,checkOpts);
        futureCheckSeconds = toc(checkClock);
        rngAfterCheck = rng;
        require(isequal(rngBefore,rngAfterCheck), ...
            'Perturbation check did not restore the caller RNG state.');
        checkNames = {'FirstForecastMW';'FirstOriginCVScores';'InitialCalibrationScores'};
        difference = [max(abs(B.PredictionMW(1)-Bcheck.PredictionMW)); ...
            max(abs(B.CycleCVScores(1,:)-Bcheck.CycleCVScores),[],'all'); ...
            max(abs(B.CalibrationTable.CV_MSE_MW2- ...
                Bcheck.CalibrationTable.CV_MSE_MW2),[],'all')];
        tolerance = [1e-7;1e-7;1e-7];
        checks = table(checkNames,difference,tolerance,difference<=tolerance, ...
            'VariableNames',{'Quantity','MaxAbsoluteDifference','AbsoluteTolerance','Passed'});
        writetable(checks,fullfile(reportDir,'step6_future_perturbation_checks.csv'));
        require(all(checks.Passed) && ...
            B.NumLearningCycles(1)==Bcheck.NumLearningCycles && ...
            B.SelectedStructureIndex==Bcheck.SelectedStructureIndex && ...
            isequal(B.RawIndex(1),Bcheck.RawIndex) && ...
            isequal(A.StaticCalibrationRawIndex,Acheck.StaticCalibrationRawIndex) && ...
            B.TargetMW(1)~=Bcheck.TargetMW(1), ...
            'Changing the first target/future loads changed its forecast or tuning.');
        require(strcmp(sourceSnapshot,fileread(corePath)), ...
            'The LSBoost source changed during the pilot. Preserve this folder and inspect.');

        linearPilot = struct('ModelNames',{reference.ModelNames}, ...
            'TimeUTC',reference.TimeUTC(1:24),'RawIndex',reference.RawIndex(1:24), ...
            'TargetMW',reference.TargetMW(1:24), ...
            'PredictionMW',reference.PredictionMW(1:24,:), ...
            'StaticAlpha',reference.StaticAlpha);
        predictions = table(B.RawIndex,utcText(B.TimeUTC), ...
            utcText(D.intervalEndUTC(B.RawIndex)),B.TargetMW, ...
            'VariableNames',{'RawIndex','IntervalStartUTC','IntervalEndUTC','TargetMW'});
        for m=1:numel(reference.ModelNames)
            predictions.([reference.ModelNames{m} '_PredictionMW']) = ...
                reference.PredictionMW(1:24,m);
        end
        predictions.LSBoost_PredictionMW = B.PredictionMW;
        predictions.LSBoost_ErrorMW = B.ErrorMW;
        writetable(predictions,fullfile(reportDir,'step6_pilot_predictions.csv'));
        parameters = table(B.RawIndex,utcText(B.TimeUTC),B.NumLearningCycles, ...
            B.CycleAtLowerBoundary,B.CycleAtUpperBoundary,B.RuntimeSeconds, ...
            B.CVSeconds,B.FitPredictSeconds,A.ForecastTrainingFirstRawIndex, ...
            A.ForecastTrainingLastRawIndex, ...
            'VariableNames',{'RawIndex','IntervalStartUTC','NumLearningCycles', ...
            'AtLowerCycleBoundary','AtUpperCycleBoundary','RuntimeSeconds', ...
            'CVSeconds','FitPredictSeconds','TrainingFirstRawIndex','TrainingLastRawIndex'});
        for j=1:numel(A.Config.CycleGrid)
            parameters.(sprintf('CV_MSE_Trees%d',A.Config.CycleGrid(j))) = B.CycleCVScores(:,j);
        end
        writetable(parameters,fullfile(reportDir,'step6_pilot_parameters.csv'));
        writetable(B.CalibrationTable,fullfile(reportDir,'step6_initial_calibration.csv'));
        writetable(A.ChronologicalFolds,fullfile(reportDir,'step6_chronological_folds.csv'));
        allPredictions = [reference.PredictionMW(1:24,:) B.PredictionMW];
        names = [reference.ModelNames {'LSBoost'}];
        e = B.TargetMW-allPredictions;
        metrics = table(names(:),repmat(24,numel(names),1), ...
            sqrt(mean(e.^2,1))',mean(abs(e),1)', ...
            (100*mean(abs(e./B.TargetMW),1))', ...
            'VariableNames',{'Model','N','RMSE_MW','MAE_MW','MAPE_pct'});
        writetable(metrics,fullfile(reportDir,'step6_accuracy_PILOT_ONLY.csv'));

        P = struct('Revision','1.0','Status','PASS','Model','LSBoost', ...
            'ForecastOrigins',24,'FullPeriodForecastsRun',false, ...
            'ExpectedFullForecastOrigins',34343,'CoreCallWallSeconds',coreCallSeconds, ...
            'CalibrationSeconds',B.CalibrationSeconds, ...
            'ForecastLoopSeconds',sum(B.RuntimeSeconds), ...
            'MeanOriginSeconds',mean(B.RuntimeSeconds), ...
            'MedianOriginSeconds',median(B.RuntimeSeconds), ...
            'MinOriginSeconds',min(B.RuntimeSeconds),'MaxOriginSeconds',max(B.RuntimeSeconds), ...
            'PrefixCheckSeconds',A.PrefixCheck.Seconds, ...
            'FuturePerturbationCheckSeconds',futureCheckSeconds, ...
            'FuturePerturbationPassed',true,'RNGRestorationPassed',true);
        P.RoughFullFittingHours = (B.CalibrationSeconds+34343*mean(B.RuntimeSeconds))/3600;
        P.RuntimeScope = ['Same-machine serial planning estimate: initial calibration once ' ...
            'plus 34343 times the pilot mean origin time. Excludes verification, ' ...
            'checkpoint/output costs and pauses. Later tree counts and fit costs can differ.'];
        P.Scope = ['Execution, causality, alignment and runtime pilot only. ' ...
            'Do not select settings from these forecast errors. ' ...
            'LSBoost is a nonlinear tree benchmark, not XGBoost or LightGBM.'];
        futureCheck = struct('FirstChangedRawIndex',firstRaw, ...
            'Perturbation','y(first:end).*exp(0.05*cos((0:nFuture-1)''))', ...
            'OriginalFirstForecastMW',B.PredictionMW(1), ...
            'PerturbedFirstForecastMW',Bcheck.PredictionMW, ...
            'Checks',checks,'Seconds',futureCheckSeconds);
        save(fullfile(reportDir,'step6_nonlinear_pilot_results.mat'), ...
            'B','A','P','linearPilot','futureCheck','sourceProtocol','sourceMetadata','-v7.3');

        summary = sprintf([ ...
            'VA-REN REVISION: STEP 6 NONLINEAR BENCHMARK PILOT\n' ...
            'Revision 1.0; MATLAB %s\n\n' ...
            'STEP6_STATUS: PASS\nNONLINEAR_MODEL: LSBoost\n' ...
            'FORECAST_ORIGINS: 24\nFULL_PERIOD_NONLINEAR_FORECASTS_RUN: NO\n' ...
            'PREFIX_PREDICTION_CHECK: PASS\nFUTURE_PERTURBATION_CHECK: PASS\n' ...
            'RNG_RESTORATION_CHECK: PASS\nCOMMON_ORIGINS_AND_TARGETS: PASS\n\n' ...
            'First forecast start: %s\nLast forecast start: %s\n' ...
            'Selected max splits / min leaf size: %d / %d\nFixed learning rate: %.6g\n' ...
            'Cycle candidates: 25, 50, 100, 200; retuned using past-only folds at each origin.\n' ...
            'Lower / upper cycle endpoint selections in pilot: %d / %d of 24.\n\n' ...
            'One-time structure calibration: %.3f seconds\n' ...
            '24-origin forecast-loop time: %.3f seconds\n' ...
            'Per-origin time mean / median / min / max: %.3f / %.3f / %.3f / %.3f seconds\n' ...
            'Core call wall time (including prefix check): %.3f seconds\n' ...
            'Additional future-perturbation check: %.3f seconds\n' ...
            'Rough full-period serial fitting estimate: %.2f hours\n%s\n\n' ...
            '%s\n' ...
            'Step 5 forecasts are reused; this step does not alter the completed linear run.\n' ...
            'Initial calibration losses may diagnose the prespecified grid.\n' ...
            'Pilot forecast errors and later evaluation windows must not redesign it.\n' ...
            'A cycle-boundary selection alone is not an execution failure.\n' ...
            'Target: system demand, not solar-subtracted net load.\n' ...
            'Return step6_nonlinear_pilot_results.zip before a full nonlinear run.\n'], ...
            version,char(utcText(B.TimeUTC(1))),char(utcText(B.TimeUTC(end))), ...
            B.SelectedMaxNumSplits,B.SelectedMinLeafSize,B.LearnRate, ...
            sum(B.CycleAtLowerBoundary),sum(B.CycleAtUpperBoundary), ...
            B.CalibrationSeconds,P.ForecastLoopSeconds,P.MeanOriginSeconds, ...
            P.MedianOriginSeconds,P.MinOriginSeconds,P.MaxOriginSeconds, ...
            coreCallSeconds,futureCheckSeconds,P.RoughFullFittingHours,P.RuntimeScope,P.Scope);
        writeText(fullfile(reportDir,'step6_summary.txt'),summary);
        fprintf('\n%s\n',summary);
        diary('off');
        packageFolder(reportDir,zipPath);
        fprintf('Upload ZIP: %s\n',zipPath);
    catch ME
        errorReport = getReport(ME,'extended','hyperlinks','off');
        fprintf('\nSTEP6_STATUS: FAIL\n%s\nOutput folder: %s\n',errorReport,reportDir);
        try
            writeText(fullfile(reportDir,'step6_summary.txt'),sprintf( ...
                'STEP6_STATUS: FAIL\nDo not use this pilot as validated results.\n\n%s\n',errorReport));
            diary('off');
            failureZip = fullfile(reportDir,'step6_nonlinear_pilot_failure.zip');
            packageFolder(reportDir,failureZip);
            fprintf('Upload failure ZIP: %s\n',failureZip);
        catch packagingError
            diary('off');
            fprintf('Failure ZIP could not be created: %s\n',packagingError.message);
            fprintf('Return the Command Window error and step6_console.txt.\n');
        end
        rethrow(ME);
    end
end

function [folder,referenceFile] = resolveStep5(location)
    require((ischar(location) && isrow(location)) || ...
        (isstring(location) && isscalar(location) && ~ismissing(location)), ...
        'Supply the completed Step 5 run-folder path or its full results MAT path.');
    location = char(location);
    if isfolder(location)
        folder = location;
        referenceFile = fullfile(folder,'full','varen_corrected_results.mat');
    elseif isfile(location)
        [parent,name,extension] = fileparts(location);
        [folder,subfolder] = fileparts(parent);
        require(strcmp([name extension],'varen_corrected_results.mat') && ...
            strcmp(subfolder,'full'), ...
            'Select full/varen_corrected_results.mat from Step 5, not a pilot or resume-check MAT.');
        referenceFile = location;
    else
        error('VAREN:Step6Input','Step 5 location not found: %s',location);
    end
    require(isfile(referenceFile) && isfile(fullfile(folder,'step5_inputs.mat')) && ...
        isfile(fullfile(folder,'step5_summary.txt')), ...
        'The selected folder must contain a completed Step 5 run and saved inputs.');
end

function validateReference(D,R,A,folder)
    require(contains(fileread(fullfile(folder,'step5_summary.txt')),'STEP5_STATUS: PASS'), ...
        'The selected Step 5 run has not reported PASS.');
    require(all(isfield(D,{'timeUTC','intervalEndUTC','loadMW','isObserved', ...
        'protocol','sourceMetadata'})),'Missing source variables in step5_inputs.mat.');
    require(isdatetime(D.timeUTC) && ~isempty(D.timeUTC.TimeZone) && ...
        isdatetime(D.intervalEndUTC) && ~isempty(D.intervalEndUTC.TimeZone) && ...
        iscolumn(D.timeUTC) && iscolumn(D.intervalEndUTC) && ...
        iscolumn(D.loadMW) && iscolumn(D.isObserved), ...
        'Require timezone-aware timestamp columns and column data.');
    require(numel(D.timeUTC)==43824 && numel(D.intervalEndUTC)==43824 && ...
        numel(D.loadMW)==43824 && numel(D.isObserved)==43824 && ...
        ~any(isnat(D.timeUTC)) && ~any(isnat(D.intervalEndUTC)) && ...
        all(diff(D.timeUTC)==hours(1)) && all(D.intervalEndUTC-D.timeUTC==hours(1)) && ...
        isreal(D.loadMW) && all(isfinite(D.loadMW)) && all(D.loadMW>0) && ...
        islogical(D.isObserved) && all(D.isObserved), ...
        'Unexpected source record count, interval geometry or observation values.');
    require(D.timeUTC(1)==datetime(2019,1,1,8,0,0,'TimeZone','UTC') && ...
        D.intervalEndUTC(end)==datetime(2024,1,1,8,0,0,'TimeZone','UTC'), ...
        'Unexpected frozen source coverage.');
    require(strcmp(D.sourceMetadata.canonical_csv_sha256, ...
        '249120565acab4af01f3dab853da075562b809edaf758ff0f7f7033774b33881') && ...
        strcmp(D.sourceMetadata.status,'COMPLETE_WITH_NO_GAPS_OR_DUPLICATES') && ...
        strcmp(D.protocol.TimestampProvenance,'provider_supplied_UTC_interval_start_and_end') && ...
        D.protocol.ExpectedForecasts==34343,'Unexpected source identity or protocol.');
    require(isequal(A.InputTimeUTC,D.timeUTC) && isequal(A.InputLoadMW,D.loadMW) && ...
        isequal(A.InputIsObserved,D.isObserved),'Step 5 source arrays do not agree.');
    expectedNames = {'Persistence','SeasonalNaive','Ridge','LASSO','StaticEN','FixedEN05','VAREN'};
    require(isequal(R.ModelNames,expectedNames) && isequal(R.RawIndex,(9482:43824)') && ...
        isequal(size(R.PredictionMW),[34343 7]) && ...
        all(isfinite(R.PredictionMW),'all') && all(R.PredictionMW>0,'all') && ...
        isequal(R.TargetMW,D.loadMW(R.RawIndex)) && isequal(R.TimeUTC,D.timeUTC(R.RawIndex)) && ...
        isequal(R.ErrorMW,R.TargetMW-R.PredictionMW), ...
        'Unexpected full-run origins, targets or prediction arrays.');
    require(R.StaticAlpha==1 && isequal(R.PredictionMW(:,4),R.PredictionMW(:,5)), ...
        'Expected calibrated StaticEN to coincide with LASSO in this frozen run.');
    require(A.Config.W==720 && A.Config.CalibrationRows==720 && ...
        A.Config.EvaluationWarmupRows==720 && A.Config.K==5 && ...
        A.Config.InitialTrainFraction==.5 && numel(A.PredictorNames)==70, ...
        'The benchmark requires the reviewed Step 5 training protocol.');
end

function validatePilot(D,R,L,B,A)
    rows = (9482:9505)';
    require(strcmp(B.ModelName,'LSBoost') && isequal(B.RawIndex,rows) && ...
        isequal(size(B.PredictionMW),[24 1]) && all(isfinite(B.PredictionMW)) && ...
        all(B.PredictionMW>0) && isequal(B.ErrorMW,B.TargetMW-B.PredictionMW), ...
        'Invalid nonlinear pilot prediction arrays.');
    require(isequal(B.TimeUTC,R.TimeUTC(1:24)) && ...
        isequal(B.TargetMW,R.TargetMW(1:24)) && ...
        isequal(B.TimeUTC,D.timeUTC(rows)) && isequal(B.TargetMW,D.loadMW(rows)), ...
        'LSBoost does not share the Step 5 origins and targets.');
    require(isequal(A.InputTimeUTC,D.timeUTC) && isequal(A.InputLoadMW,D.loadMW) && ...
        isequal(A.InputIsObserved,D.isObserved) && isequal(A.PredictorNames,L.PredictorNames), ...
        'Input values, observation flags or predictor definitions changed.');
    require(A.Config.W==720 && A.Config.K==5 && A.Config.CalibrationRows==720 && ...
        A.Config.EvaluationWarmupRows==720 && A.Config.InitialTrainFraction==.5 && ...
        isequal(A.Config.CycleGrid,[25 50 100 200]) && A.Config.LearnRate==.1 && ...
        isequal(A.Config.StructureGrid,[3 20;3 5;15 20;15 5]) && A.Config.MaxForecasts==24, ...
        'The nonlinear pilot differs from the prespecified protocol.');
    require(isequal(A.ModelReadyRawIndex,(8762:43824)') && ...
        isequal(A.StaticCalibrationRawIndex,(8762:9481)') && ...
        A.StaticCalibrationStartUTC==L.StaticCalibrationStartUTC && ...
        A.StaticCalibrationEndUTC==L.StaticCalibrationEndUTC && ...
        A.StaticCalibrationEndUTC<B.TimeUTC(1) && ...
        isequal(A.ForecastTrainingFirstRawIndex,rows-720) && ...
        isequal(A.ForecastTrainingLastRawIndex,rows-1), ...
        'Calibration or forecast-training windows are misaligned.');
    F = A.ChronologicalFolds;
    require(height(F)==5 && isequal(F.TrainStart,ones(5,1)) && ...
        isequal(F.TrainEnd,(360:72:648)') && ...
        isequal(F.ValidationStart,(361:72:649)') && ...
        isequal(F.ValidationEnd,(432:72:720)') && ...
        all(F.ValidationN==72),'Internal cross-validation is not the required chronological split.');
    require(A.PrefixCheck.Pass && isfinite(A.PrefixCheck.MaxAbsDifferenceZ) && ...
        A.PrefixCheck.MaxAbsDifferenceZ<=A.PrefixCheck.ToleranceZ, ...
        'Staged-tree predictions did not reproduce independently fitted shorter trees.');
    require(isequal(size(B.CycleCVScores),[24 4]) && ...
        all(isfinite(B.CycleCVScores),'all') && all(B.CycleCVScores>=0,'all') && ...
        all(ismember(B.NumLearningCycles,A.Config.CycleGrid)), ...
        'Invalid rolling tree-count selection scores.');
    [~,best] = min(B.CycleCVScores,[],2);
    grid = A.Config.CycleGrid(:);
    require(isequal(B.NumLearningCycles,grid(best)) && ...
        isequal(B.CycleAtLowerBoundary,B.NumLearningCycles==grid(1)) && ...
        isequal(B.CycleAtUpperBoundary,B.NumLearningCycles==grid(end)), ...
        'Tree counts or boundary flags do not follow the prespecified selection rule.');
    require(all(isfinite(B.RuntimeSeconds)) && all(B.RuntimeSeconds>=0) && ...
        all(isfinite(B.CVSeconds)) && all(B.CVSeconds>=0) && ...
        all(isfinite(B.FitPredictSeconds)) && all(B.FitPredictSeconds>=0) && ...
        isfinite(B.CalibrationSeconds) && B.CalibrationSeconds>=0, ...
        'Invalid timing measurements.');
end

function s = utcText(t)
    t.TimeZone = 'UTC';
    t.Format = 'yyyy-MM-dd''T''HH:mm:ss''Z''';
    s = string(t);
end

function require(condition,message)
    if ~isscalar(condition) || ~condition
        error('VAREN:Step6Validation','%s',message);
    end
end

function writeText(path,value)
    fid = fopen(path,'w');
    if fid<0, error('VAREN:Step6Write','Cannot write: %s',path); end
    cleanup = onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%s',value);
end

function packageFolder(folder,zipPath)
    files = dir(folder);
    files = files(~[files.isdir]);
    names = {files.name};
    keep = ~startsWith(names,'.') & ~endsWith(names,'.zip');
    zip(zipPath,names(keep),folder);
end

function restoreDiary(file,state)
    diary('off');
    if ~isempty(file), diary(file); end
    if strcmpi(state,'off'), diary('off'); end
end
