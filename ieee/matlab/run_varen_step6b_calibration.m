function [reportDir,zipPath] = run_varen_step6b_calibration(step6Location)
%RUN_VAREN_STEP6B_CALIBRATION Inspect a bounded wider LSBoost calibration grid.
%
% [step6bFolder,step6bZip] = run_varen_step6b_calibration(step6Folder)
% [step6bFolder,step6bZip] = run_varen_step6b_calibration() % choose pilot MAT
%
% Revision 1.0. Source-reviewed; MATLAB execution remains the user's check.
% The original initial calibration selected the upper grid count of 200
% trees. This audit adds 400/800/1600 candidates using ONLY that same initial
% calibration data. It never evaluates a forecast origin, uses pilot errors
% for tuning, automatically extends beyond 1600, or starts a full run.
%
% The wrapper explicitly removes the first evaluation target and all later
% raw observations BEFORE calling the calibration function. The original
% calibration losses/folds are reproduced as an implementation check.
% No existing Step 5 or Step 6 output is changed.

    if nargin<1 || isempty(step6Location)
        [f,p] = uigetfile('*.mat','Select step6_nonlinear_pilot_results.mat');
        if isequal(f,0)
            error('VAREN:Step6bCancelled','No Step 6 pilot MAT was selected.');
        end
        step6Location = fullfile(p,f);
    end
    [step6Folder,pilotFile] = resolveStep6(step6Location);
    corePath = which('varen_lsboost_calibration');
    require(~isempty(corePath) && exist('varen_lsboost_calibration','file')==2, ...
        'Put varen_lsboost_calibration.m beside this wrapper in the MATLAB folder.');
    wrapperPath = [mfilename('fullpath') '.m'];
    baseDir = fileparts(wrapperPath);
    [~,name] = fileparts(tempname(baseDir));
    reportDir = fullfile(baseDir,['step6b_calibration_' name]);
    [ok,msg] = mkdir(reportDir);
    if ~ok, error('VAREN:Step6bFolder','Cannot create output folder: %s',msg); end
    zipPath = fullfile(reportDir,'step6b_calibration_results.zip');
    oldDiaryFile = get(0,'DiaryFile');
    oldDiaryState = get(0,'Diary');
    diaryCleanup = onCleanup(@()restoreDiary(oldDiaryFile,oldDiaryState)); %#ok<NASGU>
    diary(fullfile(reportDir,'step6b_console.txt'));

    try
        fprintf('\nVA-REN REVISION: STEP 6b CALIBRATION-ONLY GRID AUDIT\n');
        fprintf('Revision 1.0; MATLAB %s\n',version);
        fprintf('Step 6 folder: %s\nOutput folder: %s\n',step6Folder,reportDir);
        copyfile(wrapperPath,fullfile(reportDir,'run_varen_step6b_calibration.m'));
        copyfile(corePath,fullfile(reportDir,'varen_lsboost_calibration.m'));
        sourceSnapshot = fileread(corePath);
        % Load the prior run, then immediately retain only input provenance,
        % initial calibration fields, and the passed execution status.
        % No pilot forecast/error or rolling-validation field is used.
        S = load(pilotFile,'A','B','P','sourceProtocol','sourceMetadata');
        require(all(isfield(S,{'A','B','P','sourceProtocol','sourceMetadata'})), ...
            'The selected MAT is missing Step 6 calibration or source metadata.');
        originalAudit = S.A;
        referenceTable = S.B.CalibrationTable;
        referenceFoldMSE = S.B.CalibrationFoldMSE;
        priorStatus = S.P.Status;
        sourceProtocol = S.sourceProtocol;
        sourceMetadata = S.sourceMetadata;
        clear S
        validateReference(originalAudit,referenceTable,referenceFoldMSE, ...
            priorStatus,sourceProtocol,sourceMetadata);

        % This is the actual information boundary for the fitting function.
        % Raw row 9482 is the first held-out target and is not supplied.
        timeUTC = originalAudit.InputTimeUTC(1:9481);
        loadMW = originalAudit.InputLoadMW(1:9481);
        isObserved = originalAudit.InputIsObserved(1:9481);
        expectedPredictorNames = originalAudit.PredictorNames;
        expectedFolds = originalAudit.CalibrationChronologicalFolds;
        originalVersion = originalAudit.MATLABVersion;
        clear originalAudit
        opts = struct('IsObserved',isObserved,'Verbose',true);
        startedUTC = datetime('now','TimeZone','UTC');
        save(fullfile(reportDir,'step6b_run_metadata.mat'), ...
            'step6Folder','pilotFile','corePath','sourceSnapshot','startedUTC', ...
            'sourceProtocol','sourceMetadata','originalVersion','-v7');
        writetable(referenceTable,fullfile(reportDir,'step6b_original_calibration.csv'));
        fprintf('\nHistorical input stops at 2020-01-31T08:00:00Z.\n');
        fprintf('First evaluation target at 09:00Z is excluded. Evaluation forecasts: ZERO.\n');
        fprintf('Same 720 calibration rows, four structures and five chronological folds.\n');
        fprintf('Bounded tree-count grid: 25, 50, 100, 200, 400, 800, 1600.\n');
        fprintf('The 1600-tree path is fitted once per structure/fold.\n');
        fprintf('This step reports calibration results only; no full run starts.\n\n');

        rngBefore = rng;
        callClock = tic;
        [C,A] = varen_lsboost_calibration(timeUTC,loadMW,opts);
        coreCallSeconds = toc(callClock);
        rngAfter = rng;
        require(isequal(rngBefore,rngAfter),'The calibration core did not restore caller RNG.');
        validateCalibration(C,A,timeUTC,loadMW,isObserved,expectedPredictorNames,expectedFolds);

        keys = {'StructureIndex','MaxNumSplits','MinLeafSize','LearnRate','NumLearningCycles'};
        [found,where] = ismember(referenceTable{:,keys},C.CalibrationTable{:,keys},'rows');
        require(all(found) && numel(unique(where))==16, ...
            'The expanded table does not contain every original calibration candidate.');
        oldMSE = referenceTable.CV_MSE_MW2;
        newMSE = C.CalibrationTable.CV_MSE_MW2(where);
        discrepancy = abs(newMSE-oldMSE);
        tolerance = repmat(1e-7,height(referenceTable),1);
        reproduction = referenceTable(:,keys);
        reproduction.OriginalMSE_MW2 = oldMSE;
        reproduction.ExpandedPathMSE_MW2 = newMSE;
        reproduction.AbsoluteDifference = discrepancy;
        reproduction.AbsoluteTolerance = tolerance;
        reproduction.Passed = discrepancy<=tolerance;
        foldDiscrepancy = max(abs(C.FoldMSE(:,:,1:4)-referenceFoldMSE),[],'all');
        reproductionCheck = struct('AllCandidatesPassed',all(reproduction.Passed), ...
            'MaxCandidateMSEDifference',max(discrepancy), ...
            'MaxFoldMSEDifference',foldDiscrepancy,'AbsoluteTolerance',1e-7);
        writetable(reproduction,fullfile(reportDir,'step6b_reproduction_checks.csv'));
        require(all(reproduction.Passed) && isfinite(foldDiscrepancy) && foldDiscrepancy<=1e-7, ...
            'Original calibration losses did not reproduce. Preserve this folder for inspection.');
        require(strcmp(sourceSnapshot,fileread(corePath)), ...
            'The calibration source changed during execution.');

        writetable(C.CalibrationTable,fullfile(reportDir,'step6b_expanded_calibration.csv'));
        writetable(A.Folds,fullfile(reportDir,'step6b_chronological_folds.csv'));
        candidateIndex = repelem((1:height(C.CalibrationTable))',5);
        foldIndex = repmat((1:5)',height(C.CalibrationTable),1);
        foldTable = C.CalibrationTable(candidateIndex,keys);
        foldTable.Fold = foldIndex;
        foldLoss = NaN(height(foldTable),1);
        for row=1:height(foldTable)
            j = foldTable.StructureIndex(row);
            k = foldTable.Fold(row);
            m = find(A.Config.CycleGrid==foldTable.NumLearningCycles(row),1);
            foldLoss(row) = C.FoldMSE(j,k,m);
        end
        foldTable.ValidationN = A.Folds.ValidationN(foldIndex);
        foldTable.MSE_MW2 = foldLoss;
        writetable(foldTable,fullfile(reportDir,'step6b_fold_losses.csv'));
        structureIndex = repelem((1:4)',5);
        foldIndex = repmat((1:5)',4,1);
        timing = table(structureIndex,foldIndex,reshape(C.FoldFitSeconds',[],1), ...
            reshape(C.FoldPredictSeconds',[],1),reshape(C.FoldTotalSeconds',[],1), ...
            'VariableNames',{'StructureIndex','Fold','Fit1600TreesSeconds', ...
            'AllPrefixesPredictSeconds','FoldTotalSeconds'});
        writetable(timing,fullfile(reportDir,'step6b_calibration_timing.csv'));

        P = struct('Revision','1.0','Status','PASS','ForecastOrigins',0, ...
            'CalibrationRows',720,'RawInputRows',9481, ...
            'CoreCallWallSeconds',coreCallSeconds, ...
            'CalibrationSeconds',C.CalibrationSeconds, ...
            'OriginalCalibrationReproduced',true,'RNGRestorationPassed',true, ...
            'AutomaticFullRunStarted',false,'AutomaticGridExtension',false, ...
            'MaximumAuditTrees',1600);
        P.Scope = ['One bounded pre-forecast calibration audit. The selected ' ...
            'candidate minimizes only this calibration loss; it is not an ' ...
            'evaluation result or a final rolling-budget decision.'];
        save(fullfile(reportDir,'step6b_calibration_results.mat'), ...
            'C','A','P','referenceTable','referenceFoldMSE','reproductionCheck', ...
            'sourceProtocol','sourceMetadata','-v7.3');
        upperText = 'NO';
        if C.SelectedCycleAtUpperBoundary, upperText = 'YES'; end
        summary = sprintf([ ...
            'VA-REN REVISION: STEP 6b CALIBRATION-ONLY GRID AUDIT\n' ...
            'Revision 1.0; MATLAB %s\n\n' ...
            'STEP6B_STATUS: PASS\nEVALUATION_FORECASTS_RUN: NO\n' ...
            'FORECAST_ORIGINS: 0\nINITIAL_CALIBRATION_ROWS: 720\n' ...
            'ORIGINAL_CALIBRATION_REPRODUCED: PASS\n' ...
            'PREFIX_PREDICTION_CHECK: PASS\nRNG_RESTORATION_CHECK: PASS\n\n' ...
            'Last raw input interval start: %s\nFirst evaluation interval start (excluded): %s\n' ...
            'Calibration raw rows: 8762:9481. Same five chronological folds as Step 6.\n' ...
            'Tree-count audit grid: 25, 50, 100, 200, 400, 800, 1600.\n' ...
            'Fixed learning rate: %.6g\n' ...
            'Selected calibration structure: max splits %d; minimum leaf %d.\n' ...
            'Selected calibration tree count: %d\n' ...
            'Selected calibration MSE: %.9f MW^2\n' ...
            'SELECTED_AT_1600_TREE_CAP: %s\n\n' ...
            'Maximum original-candidate MSE difference: %.17g MW^2\n' ...
            'Maximum original-fold MSE difference: %.17g MW^2\n' ...
            'Calibration time (excluding extra prefix check): %.3f seconds\n' ...
            'Core call wall time: %.3f seconds\n\n' ...
            '%s\n' ...
            'A cap selection is disclosed; no automatic expansion beyond 1600 occurs.\n' ...
            'No pilot forecast errors or later rolling evaluation windows were used.\n' ...
            'The prior full-run estimate applies to the 200-tree pilot, not this expanded grid.\n' ...
            'Review the calibration curves before freezing a full-run grid and runtime protocol.\n' ...
            'Return step6b_calibration_results.zip.\n'], ...
            version,char(utcText(A.InputTimeUTC(end))),char(utcText(A.FirstForecastUTC)), ...
            C.LearnRate,C.SelectedMaxNumSplits,C.SelectedMinLeafSize,C.SelectedNumLearningCycles, ...
            min(C.Scores,[],'all'),upperText,max(discrepancy),foldDiscrepancy, ...
            C.CalibrationSeconds,coreCallSeconds,P.Scope);
        writeText(fullfile(reportDir,'step6b_summary.txt'),summary);
        fprintf('\n%s\n',summary);
        disp(C.CalibrationTable);
        diary('off');
        packageFolder(reportDir,zipPath);
        fprintf('Upload ZIP: %s\n',zipPath);
    catch ME
        report = getReport(ME,'extended','hyperlinks','off');
        fprintf('\nSTEP6B_STATUS: FAIL\n%s\nOutput folder: %s\n',report,reportDir);
        try
            writeText(fullfile(reportDir,'step6b_summary.txt'),sprintf( ...
                'STEP6B_STATUS: FAIL\nPreserve this calibration audit for inspection.\n\n%s\n',report));
            diary('off');
            failureZip = fullfile(reportDir,'step6b_calibration_failure.zip');
            packageFolder(reportDir,failureZip);
            fprintf('Upload failure ZIP: %s\n',failureZip);
        catch packagingError
            diary('off');
            fprintf('Failure ZIP could not be created: %s\n',packagingError.message);
            fprintf('Return the complete error and step6b_console.txt.\n');
        end
        rethrow(ME);
    end
end

function [folder,matPath] = resolveStep6(location)
    require((ischar(location) && isrow(location)) || ...
        (isstring(location) && isscalar(location) && ~ismissing(location)), ...
        'Supply the completed Step 6 folder or its results MAT path.');
    location = char(location);
    if isfolder(location)
        folder = location;
        matPath = fullfile(folder,'step6_nonlinear_pilot_results.mat');
    else
        [folder,name,ext] = fileparts(location);
        require(strcmp([name ext],'step6_nonlinear_pilot_results.mat'), ...
            'Select step6_nonlinear_pilot_results.mat from the completed pilot.');
        matPath = location;
    end
    require(isfile(matPath),'The Step 6 pilot MAT was not found.');
end

function validateReference(A,T,foldMSE,status,protocol,metadata)
    require(strcmp(status,'PASS'),'The selected Step 6 pilot did not pass.');
    require(strcmp(metadata.canonical_csv_sha256, ...
        '249120565acab4af01f3dab853da075562b809edaf758ff0f7f7033774b33881') && ...
        strcmp(metadata.status,'COMPLETE_WITH_NO_GAPS_OR_DUPLICATES') && ...
        protocol.ExpectedForecasts==34343 && ...
        strcmp(protocol.TimestampProvenance,'provider_supplied_UTC_interval_start_and_end'), ...
        'Unexpected source identity or timestamp provenance.');
    require(strcmp(A.MATLABVersion,version), ...
        'Use the same MATLAB version as Step 6 for the calibration reproduction check.');
    require(isdatetime(A.InputTimeUTC) && ~isempty(A.InputTimeUTC.TimeZone) && ...
        iscolumn(A.InputTimeUTC) && numel(A.InputTimeUTC)==43824 && ...
        iscolumn(A.InputLoadMW) && numel(A.InputLoadMW)==43824 && ...
        iscolumn(A.InputIsObserved) && numel(A.InputIsObserved)==43824, ...
        'Unexpected saved source arrays.');
    require(isequal(A.StaticCalibrationRawIndex,(8762:9481)') && ...
        A.Config.CalibrationRows==720 && A.Config.W==720 && A.Config.K==5 && ...
        A.Config.InitialTrainFraction==.5 && A.Config.LearnRate==.1 && ...
        A.Config.RandomSeed==451 && isequal(A.Config.CycleGrid,[25 50 100 200]) && ...
        isequal(A.Config.StructureGrid,[3 20;3 5;15 20;15 5]) && ...
        numel(A.PredictorNames)==70,'Unexpected original calibration protocol.');
    require(istable(T) && height(T)==16 && ...
        all(ismember({'StructureIndex','MaxNumSplits','MinLeafSize','LearnRate', ...
        'NumLearningCycles','CV_MSE_MW2'},T.Properties.VariableNames)) && ...
        all(isfinite(T.CV_MSE_MW2)) && all(T.CV_MSE_MW2>=0) && ...
        isequal(size(foldMSE),[4 5 4]) && all(isfinite(foldMSE),'all') && ...
        all(foldMSE>=0,'all'),'Invalid saved initial calibration losses.');
end

function validateCalibration(C,A,t,y,observed,predictorNames,folds)
    require(C.ForecastOrigins==0 && isequal(A.InputTimeUTC,t) && ...
        isequal(A.InputLoadMW,y) && isequal(A.InputIsObserved,observed) && ...
        numel(y)==9481 && isequal(A.CalibrationRawIndex,(8762:9481)') && ...
        A.InputTimeUTC(end)<A.FirstForecastUTC, ...
        'Calibration input boundary changed or an evaluation origin was used.');
    require(isequal(A.PredictorNames,predictorNames) && isequal(A.Folds,folds) && ...
        isequal(A.Config.StructureGrid,[3 20;3 5;15 20;15 5]) && ...
        isequal(A.Config.CycleGrid,[25 50 100 200 400 800 1600]) && ...
        A.Config.LearnRate==.1 && A.Config.RandomSeed==451 && ...
        A.Config.CalibrationRows==720 && A.Config.K==5, ...
        'Predictors, chronological folds or fixed grid changed.');
    require(isequal(size(C.Scores),[4 7]) && isequal(size(C.FoldMSE),[4 5 7]) && ...
        all(isfinite(C.Scores),'all') && all(C.Scores>=0,'all') && ...
        all(isfinite(C.FoldMSE),'all') && all(C.FoldMSE>=0,'all') && ...
        height(C.CalibrationTable)==28, 'Invalid expanded calibration losses.');
    for j=1:4
        pooled = (A.Folds.ValidationN'*squeeze(C.FoldMSE(j,:,:)))/sum(A.Folds.ValidationN);
        require(max(abs(pooled-C.Scores(j,:)))<=1e-7, ...
            'Pooled candidate losses do not match the saved chronological fold losses.');
    end
    [~,structure] = min(min(C.Scores,[],2));
    [~,cycle] = min(C.Scores(structure,:));
    require(C.SelectedStructureIndex==structure && ...
        C.SelectedMaxNumSplits==A.Config.StructureGrid(structure,1) && ...
        C.SelectedMinLeafSize==A.Config.StructureGrid(structure,2) && ...
        C.SelectedNumLearningCycles==A.Config.CycleGrid(cycle) && ...
        C.SelectedCycleAtUpperBoundary==(cycle==7) && ...
        C.SelectedCycleAtLowerBoundary==(cycle==1), ...
        'Selected calibration candidate or boundary flag is inconsistent.');
    require(A.PrefixCheck.Pass && isfinite(A.PrefixCheck.MaxAbsDifferenceZ) && ...
        A.PrefixCheck.MaxAbsDifferenceZ<=A.PrefixCheck.ToleranceZ, ...
        'Staged prefix predictions did not reproduce a separately fitted ensemble.');
    require(isfinite(C.CalibrationSeconds) && C.CalibrationSeconds>=0 && ...
        all(isfinite(C.FoldFitSeconds),'all') && all(C.FoldFitSeconds>=0,'all') && ...
        all(isfinite(C.FoldPredictSeconds),'all') && all(C.FoldPredictSeconds>=0,'all') && ...
        all(isfinite(C.FoldTotalSeconds),'all') && all(C.FoldTotalSeconds>=0,'all'), ...
        'Invalid calibration timing measurements.');
end

function s = utcText(t)
    t.TimeZone = 'UTC';
    t.Format = 'yyyy-MM-dd''T''HH:mm:ss''Z''';
    s = string(t);
end

function require(condition,message)
    if ~isscalar(condition) || ~condition
        error('VAREN:Step6bValidation','%s',message);
    end
end

function writeText(path,value)
    fid = fopen(path,'w');
    if fid<0, error('VAREN:Step6bWrite','Cannot write: %s',path); end
    cleanup = onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%s',value);
end

function packageFolder(folder,zipPath)
    files = dir(folder);
    files = files(~[files.isdir]);
    names = {files.name};
    keep = ~startsWith(names,'.') & ~endsWith(names,'.zip');
    zip(zipPath,names(keep),folder);
end

function restoreDiary(file,state)
    diary('off');
    if ~isempty(file), diary(file); end
    if strcmpi(state,'off'), diary('off'); end
end
