function [reportDir, zipPath] = run_varen_step4_pilot(dataFile)
%RUN_VAREN_STEP4_PILOT Run the first 24 real-data forecast origins.
%
%   [step4Folder,step4Zip] = run_varen_step4_pilot(step3DataFile)
%   [step4Folder,step4Zip] = run_varen_step4_pilot() % choose the Step 3 MAT
%
% Requires the unchanged varen_corrected_core.m used in Step 1 and the
% caiso_oasis_inputs_2019_2023.mat produced by the successful Step 3.
% Revision 1.0. Prepared and source-reviewed; MATLAB execution is the next
% validation step. No MATLAB execution is claimed by this source file.
%
% All model/tuning defaults remain unchanged: 720 training hours, 48-hour
% causal volatility, 5 chronological folds, 60 lambdas, 11 static alphas.
% Only MaxForecasts, OutputDir and Verbose are set for this pilot.
% The output is an execution/alignment/runtime check. Its 24 forecast errors
% must not select hyperparameters or support full-period accuracy claims.
% No DM/GW tests, automatic grid changes, or silent fit fallbacks are used.
%
% A fresh step4_pilot_* directory beside this wrapper receives the original
% core outputs, source snapshots, run log, timing report and upload ZIP.
% On a caught error, preserve a failure report/ZIP and rethrow the error.

    if nargin < 1 || isempty(dataFile)
        [fileName,folderName] = uigetfile('*.mat', ...
            'Select caiso_oasis_inputs_2019_2023.mat from Step 3');
        if isequal(fileName,0)
            error('VAREN:Step4Cancelled','No Step 3 MAT file was selected.');
        end
        dataFile = fullfile(folderName,fileName);
    end
    if ~(ischar(dataFile) && isrow(dataFile)) && ...
            ~(isstring(dataFile) && isscalar(dataFile) && ~ismissing(dataFile))
        error('VAREN:Step4Input','Supply one Step 3 MAT file path.');
    end
    dataFile = char(dataFile);
    if ~isfile(dataFile)
        error('VAREN:Step4Input','Step 3 MAT file not found: %s',dataFile);
    end
    corePath = which('varen_corrected_core');
    if isempty(corePath) || exist('varen_corrected_core','file') ~= 2
        error('VAREN:Step4Core', ...
            'Put the existing varen_corrected_core.m in the current MATLAB folder.');
    end

    wrapperPath = [mfilename('fullpath') '.m'];
    baseDir = fileparts(wrapperPath);
    [~,uniqueName] = fileparts(tempname(baseDir));
    reportDir = fullfile(baseDir,['step4_pilot_' uniqueName]);
    [ok,msg] = mkdir(reportDir);
    if ~ok, error('VAREN:Step4Folder','Cannot create output folder: %s',msg); end
    zipPath = fullfile(reportDir,'step4_pilot_results.zip');
    logPath = fullfile(reportDir,'step4_console.txt');

    oldDiaryFile = get(0,'DiaryFile');
    oldDiaryState = get(0,'Diary');
    diaryCleanup = onCleanup(@()restoreDiary(oldDiaryFile,oldDiaryState)); %#ok<NASGU>
    diary(logPath);
    boundaryState = warning('query','VAREN:LambdaBoundary');
    warningCleanup = onCleanup(@()warning(boundaryState)); %#ok<NASGU>
    warning('on','VAREN:LambdaBoundary');

    try
        fprintf('\nVA-REN REVISION: STEP 4 REAL-DATA PILOT\n');
        fprintf('Revision 1.0; MATLAB %s\n',version);
        fprintf('Input MAT: %s\nCore: %s\nOutput folder: %s\n', ...
            dataFile,corePath,reportDir);
        copyfile(wrapperPath,fullfile(reportDir,'run_varen_step4_pilot.m'));
        copyfile(corePath,fullfile(reportDir,'varen_corrected_core.m'));

        D = load(dataFile,'timeUTC','intervalEndUTC','loadMW','isObserved', ...
            'opts','protocol','sourceMetadata');
        checkInput(D);
        % Construct only the already validated input options and run controls.
        opts = struct('IsObserved',D.isObserved, ...
            'VolCalibrationYear',2019,'FirstEvaluationYear',2020, ...
            'LastEvaluationYear',2023,'MaxForecasts',24, ...
            'OutputDir',reportDir,'Verbose',true);
        sourceProtocol = D.protocol;
        sourceMetadata = D.sourceMetadata;
        startedUTC = datetime('now','TimeZone','UTC');
        save(fullfile(reportDir,'step4_run_metadata.mat'), ...
            'dataFile','corePath','opts','sourceProtocol','sourceMetadata','startedUTC','-v7');

        fprintf('\n24 origins; 7 models; full corrected-core defaults.\n');
        fprintf('720 training hours; 5 chronological folds; 60 lambdas; 11 static alphas.\n');
        fprintf('Initial static-alpha tuning may be quiet before the first progress line.\n');
        fprintf('The core prints progress after origins 1 and 24.\n');
        fprintf('Lambda-endpoint warnings are recorded; fitting errors stop the pilot.\n\n');
        coreClock = tic;
        [R,A] = varen_corrected_core(D.timeUTC,D.loadMW,opts);
        coreCallSeconds = toc(coreClock);
        validatePilot(D,R,A);

        coreFiles = {'varen_corrected_results.mat','aligned_predictions.csv', ...
            'parameters_and_runtime.csv','accuracy_common_sample.csv', ...
            'accuracy_by_clock_window.csv','volatility_diagnostics.csv', ...
            'static_alpha_calibration.csv'};
        for j = 1:numel(coreFiles)
            require(isfile(fullfile(reportDir,coreFiles{j})), ...
                ['Missing core output: ' coreFiles{j}]);
        end

        originSeconds = sum(R.RuntimeSeconds,2);
        timingByModel = table(R.ModelNames(:),sum(R.RuntimeSeconds,1)', ...
            mean(R.RuntimeSeconds,1)',median(R.RuntimeSeconds,1)', ...
            min(R.RuntimeSeconds,[],1)',max(R.RuntimeSeconds,[],1)', ...
            'VariableNames',{'Model','PilotTotalSeconds','MeanSecondsPerOrigin', ...
            'MedianSecondsPerOrigin','MinSecondsPerOrigin','MaxSecondsPerOrigin'});
        writetable(timingByModel,fullfile(reportDir,'step4_timing_by_model.csv'));
        endpointReport = table(R.ModelNames(3:7)', ...
            sum(R.LambdaAtGridBoundary(:,3:7),1)', ...
            mean(R.LambdaAtGridBoundary(:,3:7),1)', ...
            'VariableNames',{'Model','EndpointSelections','EndpointFraction'});
        writetable(endpointReport,fullfile(reportDir,'step4_lambda_endpoints.csv'));
        % Explicit UTC text makes the clock convention visible outside MATLAB.
        timestampCheck = table(R.RawIndex,utcText(R.TimeUTC), ...
            utcText(D.intervalEndUTC(R.RawIndex)),R.TargetMW, ...
            'VariableNames',{'RawIndex','IntervalStartUTC','IntervalEndUTC','TargetMW'});
        writetable(timestampCheck,fullfile(reportDir,'step4_forecast_intervals.csv'));

        P = struct('Revision','1.0','Status','PASS','ForecastOrigins',24, ...
            'ModelCount',7,'ExpectedFullForecastOrigins',34343, ...
            'CoreCallWallSeconds',coreCallSeconds,'CoreReportedSeconds',R.TotalSeconds, ...
            'StaticAlphaCalibrationSeconds',R.StaticAlphaCalibrationSeconds, ...
            'ForecastLoopSeconds',sum(originSeconds), ...
            'MeanOriginSeconds',mean(originSeconds), ...
            'MedianOriginSeconds',median(originSeconds), ...
            'MinOriginSeconds',min(originSeconds),'MaxOriginSeconds',max(originSeconds));
        P.RoughFullFittingHours = (R.StaticAlphaCalibrationSeconds + ...
            34343*mean(originSeconds))/3600;
        P.RuntimeEstimateScope = ['Same-machine serial planning estimate only: ' ...
            'static-alpha calibration once plus 34343 times pilot mean per-origin fitting time. ' ...
            'Excludes other preprocessing/output costs and does not predict later solver difficulty.'];
        P.PilotScope = ['Execution, alignment and runtime diagnostic only. ' ...
            'No accuracy superiority, significance claim or hyperparameter selection from pilot errors.'];
        P.FirstForecastUTC = R.TimeUTC(1);
        P.LastForecastUTC = R.TimeUTC(end);
        save(fullfile(reportDir,'step4_pilot_report.mat'), ...
            'P','timingByModel','endpointReport','-v7');

        summary = sprintf([ ...
            'VA-REN REVISION: STEP 4 REAL-DATA PILOT\nRevision 1.0; MATLAB %s\n\n' ...
            'STEP4_STATUS: PASS\nFORECAST_ORIGINS: 24\nMODELS: 7\n' ...
            'FULL_PERIOD_FORECASTS_RUN: NO\n\n' ...
            'First forecast interval start: %s\nLast forecast interval start: %s\n' ...
            'Expected raw indices: 9482:9505. All 24 local hours represented once.\n' ...
            'All 168 predictions are finite and positive, with common targets and origins.\n' ...
            'Input/target alignment, naive forecasts, past-only variance and alpha checked.\n' ...
            'Full defaults, calibration dates, parameter domains and saved outputs checked.\n\n' ...
            'Core call wall time, including core output writing: %.3f seconds\n' ...
            'Initial static-alpha calibration: %.3f seconds\n' ...
            'Summed forecast-loop fitting time: %.3f seconds\n' ...
            'Per-origin fitting time, mean / median / min / max: %.3f / %.3f / %.3f / %.3f seconds\n' ...
            'Rough full-period serial fitting estimate: %.2f hours\n' ...
            '%s\n\n' ...
            'Selected static alpha: %.6g\n' ...
            'Lambda-endpoint counts are in step4_lambda_endpoints.csv.\n' ...
            'An endpoint warning alone does not fail this execution check.\n' ...
            'Any common-grid change must use only data before the first pilot forecast origin.\n' ...
            'Do not use pilot errors or later rolling windows to redesign that grid.\n\n' ...
            '%s\n' ...
            'Accuracy tables and clock-window subsets are pilot diagnostics only.\n' ...
            'TimestampUTC and TimestampPT in core CSVs are interval STARTS.\n' ...
            'The MAT file retains timezone-aware dates; the extra intervals CSV uses explicit Z.\n' ...
            'Return step4_pilot_results.zip before the full-period forecasting step.\n'], ...
            version,char(utcText(R.TimeUTC(1))),char(utcText(R.TimeUTC(end))), ...
            coreCallSeconds,R.StaticAlphaCalibrationSeconds,P.ForecastLoopSeconds, ...
            P.MeanOriginSeconds,P.MedianOriginSeconds,P.MinOriginSeconds,P.MaxOriginSeconds, ...
            P.RoughFullFittingHours,P.RuntimeEstimateScope,R.StaticAlpha,P.PilotScope);
        writeText(fullfile(reportDir,'step4_summary.txt'),summary);
        fprintf('\n%s\n',summary);
        disp(timingByModel);
        disp(endpointReport);
        diary('off'); % Flush the log before including it in the ZIP.
        packageFolder(reportDir,zipPath);
        fprintf('Upload ZIP: %s\n',zipPath);
    catch ME
        errorReport = getReport(ME,'extended','hyperlinks','off');
        fprintf('\nSTEP4_STATUS: FAIL\n%s\nOutput folder: %s\n',errorReport,reportDir);
        try
            writeText(fullfile(reportDir,'step4_summary.txt'),sprintf( ...
                'STEP4_STATUS: FAIL\nDo not use this run as validated results.\n\n%s\n',errorReport));
            diary('off');
            failureZip = fullfile(reportDir,'step4_pilot_failure.zip');
            packageFolder(reportDir,failureZip);
            fprintf('Upload failure ZIP: %s\n',failureZip);
        catch packagingError
            diary('off');
            fprintf('Failure ZIP could not be created: %s\n',packagingError.message);
            fprintf('Return the Command Window error and step4_console.txt.\n');
        end
        rethrow(ME);
    end
end

function checkInput(D)
    require(all(isfield(D,{'timeUTC','intervalEndUTC','loadMW','isObserved', ...
        'opts','protocol','sourceMetadata'})),'Missing Step 3 variables.');
    require(isdatetime(D.timeUTC) && ~isempty(D.timeUTC.TimeZone) && ...
        isdatetime(D.intervalEndUTC) && ~isempty(D.intervalEndUTC.TimeZone), ...
        'Step 3 timestamps must retain their time zones.');
    require(iscolumn(D.timeUTC) && iscolumn(D.intervalEndUTC) && ...
        iscolumn(D.loadMW) && iscolumn(D.isObserved),'Expected column vectors.');
    require(numel(D.timeUTC)==43824 && numel(D.intervalEndUTC)==43824 && ...
        numel(D.loadMW)==43824 && numel(D.isObserved)==43824, ...
        'Expected all 43824 physical-hour observations.');
    require(~any(isnat(D.timeUTC)) && ~any(isnat(D.intervalEndUTC)) && ...
        all(diff(D.timeUTC)==hours(1)) && ...
        all(D.intervalEndUTC-D.timeUTC==hours(1)), ...
        'Provider UTC intervals must be consecutive one-hour intervals.');
    require(D.timeUTC(1)==datetime(2019,1,1,8,0,0,'TimeZone','UTC') && ...
        D.intervalEndUTC(end)==datetime(2024,1,1,8,0,0,'TimeZone','UTC'), ...
        'Unexpected start/end of the frozen OASIS series.');
    require(isnumeric(D.loadMW) && isreal(D.loadMW) && ...
        all(isfinite(D.loadMW)) && all(D.loadMW>0) && ...
        islogical(D.isObserved) && all(D.isObserved), ...
        'Require finite positive published loads and true logical observation flags.');
    p = D.protocol;
    require(strcmp(p.TimestampProvenance,'provider_supplied_UTC_interval_start_and_end') && ...
        p.InputRows==43824 && p.ModelReadyRows==35063 && p.ExpectedForecasts==34343 && ...
        p.VolatilityCalibrationYear==2019 && p.VolatilityCalibrationWindows==8711 && ...
        isequal(p.EvaluationYears,2020:2023) && p.WarmupRows==720 && ...
        p.AnnualLagHours==8760 && p.VolatilityWindowHours==48, ...
        'Step 3 protocol differs from the reviewed source protocol.');
    require(strcmp(D.sourceMetadata.status,'COMPLETE_WITH_NO_GAPS_OR_DUPLICATES') && ...
        strcmp(D.sourceMetadata.canonical_csv_sha256, ...
        '249120565acab4af01f3dab853da075562b809edaf758ff0f7f7033774b33881'), ...
        'Unexpected frozen-source identity in Step 3 metadata.');
    require(D.opts.VolCalibrationYear==2019 && D.opts.FirstEvaluationYear==2020 && ...
        D.opts.LastEvaluationYear==2023 && isequal(D.opts.IsObserved,D.isObserved), ...
        'Prepared input options do not match the reviewed protocol.');
end

function validatePilot(D,R,A)
    expectedNames = {'Persistence','SeasonalNaive','Ridge','LASSO', ...
        'StaticEN','FixedEN05','VAREN'};
    rows = (9482:9505)';
    require(isequal(R.ModelNames,expectedNames) && isequal(R.RawIndex,rows), ...
        'Unexpected model order or forecast raw indices.');
    require(isequal(size(R.PredictionMW),[24 7]) && ...
        isequal(size(R.ErrorMW),[24 7]) && ...
        all(isfinite(R.PredictionMW(:))) && all(R.PredictionMW(:)>0), ...
        'Expected 24-by-7 finite positive forecasts.');
    require(isequal(R.TimeUTC,D.timeUTC(rows)) && ...
        isequal(R.TargetMW,D.loadMW(rows)) && ...
        isequal(R.ErrorMW,R.TargetMW-R.PredictionMW), ...
        'Forecast timestamps, targets or errors are misaligned.');
    require(R.TimeUTC(1)==datetime(2020,1,31,9,0,0,'TimeZone','UTC') && ...
        R.TimeUTC(end)==datetime(2020,2,1,8,0,0,'TimeZone','UTC') && ...
        isequal(sort(hour(R.TimeLocal)),(0:23)'), ...
        'Unexpected pilot calendar coverage.');
    require(isequal(R.PredictionMW(:,1),D.loadMW(rows-1)) && ...
        isequal(R.PredictionMW(:,2),D.loadMW(rows-168)), ...
        'Persistence or seasonal-naive reference is misaligned.');
    require(isequal(A.InputTimeUTC,D.timeUTC) && isequal(A.InputLoadMW,D.loadMW) && ...
        isequal(A.InputIsObserved,D.isObserved),'Core input provenance changed.');

    expected = struct('W',720,'Wv',48,'K',5,'CalibrationRows',720, ...
        'EvaluationWarmupRows',720,'InitialTrainFraction',.5,'AlphaFloor',.001, ...
        'FixedAlpha',.5,'AlphaGrid',[.05 .1 .2 .3 .4 .5 .6 .7 .8 .9 1], ...
        'LambdaGrid',logspace(-5,2,60),'VolCalibrationYear',2019, ...
        'FirstEvaluationYear',2020,'LastEvaluationYear',2023, ...
        'MaxForecasts',24,'RelTol',1e-6,'MaxIter',100000);
    fields = fieldnames(expected);
    for j = 1:numel(fields)
        f = fields{j};
        require(isequal(A.Config.(f),expected.(f)),['Changed core setting: ' f]);
    end
    require(numel(A.PredictorNames)==70 && A.VolatilityCalibrationCount==8711 && ...
        isfinite(A.VolatilityCalibrationMin) && isfinite(A.VolatilityCalibrationMax) && ...
        A.VolatilityCalibrationMax>A.VolatilityCalibrationMin && ...
        A.VolatilityCalibrationEndUTC<D.protocol.FirstModelReadyUTC && ...
        A.StaticCalibrationStartUTC==datetime(2020,1,1,9,0,0,'TimeZone','UTC') && ...
        A.StaticCalibrationEndUTC==datetime(2020,1,31,8,0,0,'TimeZone','UTC'), ...
        'Unexpected predictors or calibration window.');

    v = zeros(24,1);
    for j = 1:24
        r = rows(j);
        % Exactly 48 changes ending at r-1; target r is never used.
        v(j) = var(100*diff(log(D.loadMW(r-49:r-1))),0);
    end
    compareClose(A.ForecastVolatility,v,'Causal variance mismatch.');
    u = (v-A.VolatilityCalibrationMin)/(A.VolatilityCalibrationMax-A.VolatilityCalibrationMin);
    vn = min(1,max(0,u));
    va = max(.001,1-vn);
    compareClose(A.ForecastUnclippedVolatility,u,'Unclipped volatility mismatch.');
    compareClose(A.ForecastNormalizedVolatility,vn,'Normalized volatility mismatch.');
    compareClose(A.ForecastAlpha,va,'Volatility-to-alpha mapping mismatch.');

    for f = {'Alpha','Lambda','ActiveSetSize','RuntimeSeconds','LambdaAtGridBoundary'}
        require(isequal(size(R.(f{1})),[24 7]),['Unexpected array size: ' f{1}]);
    end
    a = R.Alpha(:,3:7); lam = R.Lambda(:,3:7); active = R.ActiveSetSize(:,3:7);
    require(all(isfinite(a(:))) && all(a(:)>=0 & a(:)<=1) && ...
        all(isfinite(lam(:))) && all(lam(:)>0) && ...
        all(ismember(lam(:),A.Config.LambdaGrid)), ...
        'Penalized parameters are invalid or outside the fixed lambda grid.');
    require(ismember(R.StaticAlpha,A.Config.AlphaGrid) && ...
        all(R.Alpha(:,3)==0) && all(R.Alpha(:,4)==1) && ...
        all(R.Alpha(:,5)==R.StaticAlpha) && all(R.Alpha(:,6)==.5), ...
        'Fixed-model alpha values differ from their definitions.');
    compareClose(R.Alpha(:,7),va,'Forecast VA alpha mismatch.');
    require(all(isfinite(active(:))) && all(active(:)>=0 & active(:)<=70) && ...
        all(active(:)==floor(active(:))),'Invalid active-set sizes.');
    require(isequal(R.LambdaAtGridBoundary(:,3:7), ...
        lam==min(A.Config.LambdaGrid) | lam==max(A.Config.LambdaGrid)), ...
        'Lambda endpoint flags disagree with selected penalties.');
    require(all(isfinite(R.RuntimeSeconds(:))) && all(R.RuntimeSeconds(:)>=0) && ...
        isfinite(R.StaticAlphaCalibrationSeconds) && R.StaticAlphaCalibrationSeconds>=0 && ...
        isfinite(R.TotalSeconds) && R.TotalSeconds>=0,'Invalid runtime measurements.');
    require(height(R.Metrics)==7 && all(R.Metrics.N==24) && ...
        all(isfinite(R.Metrics.RMSE_MW)) && ...
        height(R.AlphaCalibrationTable)==11 && ...
        all(isfinite(R.AlphaCalibrationTable.MinCVLevelMSE)), ...
        'Unexpected accuracy/calibration table or invalid losses.');
end

function compareClose(actual,expected,message)
    require(isequal(size(actual),size(expected)) && all(isfinite(actual(:))) && ...
        max(abs(actual(:)-expected(:))) <= 1e-9*max(1,max(abs(expected(:)))),message);
end

function require(condition,message)
    if ~isscalar(condition) || ~condition
        error('VAREN:Step4Validation','%s',message);
    end
end

function s = utcText(t)
    t.TimeZone = 'UTC';
    t.Format = 'yyyy-MM-dd HH:mm:ss';
    s = replace(string(t),' ','T') + "Z";
end

function writeText(path,value)
    [fid,msg] = fopen(path,'w','n','UTF-8');
    if fid < 0, error('VAREN:Step4Write','Cannot write report: %s',msg); end
    closeFile = onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%s',value);
end

function packageFolder(folder,zipPath)
    files = dir(folder);
    names = {files(~[files.isdir]).name};
    names = names(~endsWith(names,'.zip','IgnoreCase',true));
    zip(zipPath,names,folder);
end

function restoreDiary(oldFile,oldState)
    diary('off');
    if strcmp(oldState,'on'), diary(oldFile); end
end
